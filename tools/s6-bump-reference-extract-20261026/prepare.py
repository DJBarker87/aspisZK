#!/usr/bin/env python3
"""Extract exactly the owned reference already checked against the SDK."""
from pathlib import Path
import hashlib,json,sys
R=Path(__file__).resolve().parents[2];D=Path(__file__).resolve().parent
O=Path(sys.argv[1]).resolve();O.mkdir();(O/'input/src').mkdir(parents=True)
source=(R/'tools/s6-bump-step-20261026/proof.rs').read_text()
start=source.index('pub fn step(');brace=source.index('{',start);depth=1;end=brace+1
while depth:
    depth+=(source[end]=='{')-(source[end]=='}');end+=1
body=source[start:end]
(O/'input/src/lib.rs').write_text(body+'\n')
(O/'input/Cargo.toml').write_text('[package]\nname="s6-bump-owned-reference"\nversion="0.1.0"\nedition="2021"\n[workspace]\n[profile.release]\nopt-level=3\noverflow-checks=true\n')
(O/'input/Cargo.lock').write_text('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "s6-bump-owned-reference"\nversion = "0.1.0"\n')
(O/'nuc.py').write_bytes((D/'nuc.py').read_bytes())
(O/'binding.json').write_text(json.dumps({'schema':'focused-extractor-proof-packet-v1',
    'source':'tools/s6-bump-step-20261026/proof.rs','body_sha256':hashlib.sha256(body.encode()).hexdigest(),
    'body_copied_verbatim':True,'source_edits':[]},indent=2)+'\n')
(O/'plan.json').write_text(json.dumps({'files':{str(p.relative_to(O)):hashlib.sha256(p.read_bytes()).hexdigest()for p in sorted(O.rglob('*'))if p.is_file()}},indent=2)+'\n')
print(str(O))

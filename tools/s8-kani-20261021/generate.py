#!/usr/bin/env python3
"""Lift literal frozen S8 items; check every source/reference pin before gates."""
from pathlib import Path
import hashlib,json,subprocess,sys
R=Path(__file__).resolve().parents[2];T=Path(__file__).resolve().parent
E=R/'docs/research/100bit-spend-path-20261013/evidence/s8-kani-20261021';E.mkdir(exist_ok=True)
V=R/'crates/aspis-r1-cost-probe/src/verifier.rs';C=V.with_name('compact.rs');pins={};items={}
def sha(b):return hashlib.sha256(b).hexdigest()
def item(p,marker):
 s=p.read_text();a=s.index(marker);b=s.index('{',a);depth=1;end=b+1
 while depth:
  depth+=(s[end]=='{')-(s[end]=='}');end+=1
 text=s[a:end];items[str(p.relative_to(R))+':'+marker]={'sha256':sha(text.encode()),'start_line':s[:a].count('\n')+1,'end_line':s[:end].count('\n')+1}
 pins[str(p.relative_to(R))]=sha(p.read_bytes());return text
frozen='// Literal frozen items; generated by generate.py. No deployed edits.\n'
frozen+='#[derive(Debug,Clone,Copy,PartialEq,Eq)]\n'+item(C,'pub enum CodecError')+'\n'
frozen+=item(C,'pub fn check_values(')+'\n'
frozen+=item(V,'struct BatchedWeights')+'\nimpl BatchedWeights {\n'+item(V,'fn value(&self,index:usize)')+'\n'+item(V,'fn finish(&self,weights:')+'\n}\n'
for m in ['fn residue_limb_at','fn power_limb_at','fn update_residue_row']:frozen+=item(V,m)+'\n'
path=T/'src/frozen.rs'
if '--check' in sys.argv:assert path.read_text()==frozen
else:path.write_text(frozen)
for p in [R/'crates/aspis-core/src/field.rs']:pins[str(p.relative_to(R))]=sha(p.read_bytes())
for path,h in pins.items():assert sha(subprocess.check_output(['git','show','b2727acd3:'+path],cwd=R))==h,path
changed=subprocess.check_output(['git','diff','--name-only','75c037e96','--','crates','programs'],cwd=R,text=True).splitlines();assert not changed,changed
references={str(p.relative_to(T)):sha(p.read_bytes()) for p in sorted((T/'src').glob('*.rs')) if p.name not in ['proofs.rs','tests.rs']}
manifest={'frozen_revision':'b2727acd3abf79315d18b754a260f58f4b1c6326','worker_base':'75c037e96','source_files':pins,'literal_items':items,'reference_sources':references,'shipped_changes':changed,'semantics_note':'check_values ignores a remainder shorter than 16 bytes; finish visits destination length (raw may be longer)'}
p=E/'source-binding.json'
if '--check' in sys.argv:assert json.loads(p.read_text())==manifest
else:p.write_text(json.dumps(manifest,indent=2)+'\n')
print('S8 frozen slices and reference hashes match; shipped files unchanged')

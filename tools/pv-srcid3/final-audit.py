#!/usr/bin/env python3
"""Compile-free source inventory; kernel audit remains a separate host target."""
import hashlib,json,pathlib,re
root=pathlib.Path(__file__).resolve().parents[2]
lean=root/'docs/research/v8-r0-zk-20261009/lean'
e=root/'evidence/pv-srcid3-20261026'
pending=e/'pending-proof-sources'
sources={f'R1Z.{p.stem}':p for p in sorted((lean/'R1Z').glob('PV_Src_*.lean')) if p.stem!='PV_Src_FinalAudit'}
for p in sorted(pending.glob('*.lean.txt')):
 if p.name!='PV_Src_FinalAudit.lean.txt':sources['R1Z.'+p.name.removesuffix('.lean.txt')]=p
imports={}
def read_imports(p):return re.findall(r'^import\s+(\S+)',p.read_text(),re.M)
def closure(m,seen):
 if m in seen:return
 seen.add(m)
 p=sources.get(m,lean/(m.replace('.','/')+'.lean'))
 if p.exists():
  imports[m]=read_imports(p)
  for dep in imports[m]:closure(dep,seen)
rows=[];checks=set()
for m,p in sorted(sources.items()):
 s=p.read_text();ns=re.findall(r'^namespace (\S+)',s,re.M)
 theorems=re.findall(r'^[ \t]*(?:@\[[^\n]*\]\s*)?(?:theorem|lemma)\s+(\S+)',s,re.M)
 assert not theorems or len(ns)==1,(m,ns)
 names=[ns[0]+'.'+n for n in theorems]
 checks.update(names)
 for n in re.findall(r'^#print axioms (\S+)',s,re.M):
  checks.add(n if n.startswith('R1Z.') or n.startswith('R0') else ns[0]+'.'+n)
 seen=set();closure(m,seen)
 rows.append(dict(module=m,source=str(p.relative_to(root)),sha256=hashlib.sha256(p.read_bytes()).hexdigest(),theorems=names,direct_imports=imports[m],research_dependency_closure=sorted(d for d in seen if (lean/(d.replace('.','/')+'.lean')).exists() and d!=m),external_or_unresolved_imports=sorted(d for d in seen if d not in sources and not (lean/(d.replace('.','/')+'.lean')).exists())))
text='\n'.join('import '+m for m in sorted(sources))+'\n\n/-! Generated by tools/pv-srcid3/final-audit.py. Compile on the authorized host only.\nSource inventory is not a kernel replay or a source/installed-input join. -/\n\n'+'\n'.join('#print axioms '+n for n in sorted(checks))+'\n'
(pending/'PV_Src_FinalAudit.lean.txt').write_text(text)
(e/'dependency-closure.json').write_text(json.dumps(dict(status='SOURCE INVENTORY ONLY; pending kernel replay',modules=rows,axiom_checks=sorted(checks)),indent=2)+'\n')
print(f'{len(rows)} modules, {sum(len(r["theorems"]) for r in rows)} theorem declarations, {len(checks)} axiom checks')

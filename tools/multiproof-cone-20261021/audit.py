#!/usr/bin/env python3
"""Focused proof and P6-cut audit; never asserts whole-cone closure."""
from pathlib import Path
import hashlib,json,re,subprocess
R=Path(__file__).resolve().parents[2];T=Path(__file__).resolve().parent
E=R/'docs/research/100bit-spend-path-20261013/evidence/multiproof-cone-20261021'
L=E.parent.parent/'lean';BASE='ec56a3486'
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
subprocess.run(['python3','-B',str(T/'generate.py'),'--check'],check=True)
subprocess.run(['python3','-B',str(T/'stage-cache.py')],check=True)
manifest=json.loads((E/'manifest.json').read_text());current={}
allowed={'propext','Classical.choice','Quot.sound'}
for a in manifest['attempts']:
 folder=E/(a['module']+'-'+str(a['attempt']))
 assert sha(folder/'source.lean.txt')==a['source_sha256']
 if a.get('status')=='cancelled-before-compiler':
  assert not a['final_current'] and a['peak_rss_bytes'] is None;continue
 assert (folder/'receipt.json').exists()
 for field in ['argv','source_revision','exit','wall_seconds','peak_rss_bytes','swaps','axioms','deps_fingerprint']:
  assert field in a,(a['module'],field)
 assert a['swaps']==0
 if not a['final_current']:continue
 assert a['exit']==0 and not a['errors']
 source=L/(a['module'].replace('.','/')+'.lean')
 assert sha(source)==a['source_sha256']
 text=source.read_text()
 assert not re.search(r'\b(?:sorry|axiom|admit|native_decide)\b',text),source
 if a['module'].startswith(('MultiproofConeRef.','MultiproofParserRef.')):
  assert text.startswith('-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS')
 else:
  assert not re.search(r'set_option\s+(?:maxRecDepth|maxHeartbeats)',text)
  for name in re.findall(r'^(?:private )?theorem\s+(\w+)',text,re.M):
   assert '#print axioms '+name in text,(source,name)
  assert a['axioms'],source
 for line in a['axioms']:
  if 'does not depend on any axioms' in line:continue
  names={n.strip() for n in line.split('[',1)[1].rsplit(']',1)[0].split(',')}
  assert names<=allowed,(source,names)
 for dep in a['direct_imports']:assert sha(Path(dep['path']))==dep['sha256'],dep
 assert sha(Path(a['argv'][a['argv'].index('-o')+1]))==a['object_sha256']
 current[a['module']]=a
required={'MultiproofConeRef.Types','MultiproofConeRef.Funs','MultiproofParserRef.Types','MultiproofParserRef.Funs','MultiproofConeCodec','MultiproofConeHeader','MultiproofConeWordScan','MultiproofConeEndian','MultiproofConeLeaf','MultiproofConeHeight','MultiproofConeFreeze'}
assert set(current)==required,(set(current),required)
# The final source-binding checkpoint covers all remaining Kani roots.
rec=json.loads((E/'host/receipts/final-local-cuts-1/receipt.json').read_text())
assert rec['exit_status']==0 and rec['swaps']==0
assert rec['limits']=={'memory.high':str(6*2**30),'memory.max':str(8*2**30),'memory.swap.max':'0','pids.max':'64'}
roots=set(re.findall(r'--harness\s+([^\s]+)',' '.join(rec['target'])))
assert len(roots)==18,roots
log=(E/'host/receipts/final-local-cuts-1/stdout.log').read_text()
assert '18 successfully verified harnesses, 0 failures, 18 total' in log
for p,h in rec['source_sha256'].items():
 if p.endswith('.rs') or p.endswith('Cargo.toml') or p.endswith('Cargo.lock'):
  assert sha(R/p)==h,p
# Source is committed and byte-identical to the recorded Rust revision.
for p,h in rec['source_sha256'].items():
 if not (p.endswith('.rs') or p.endswith('Cargo.toml') or p.endswith('Cargo.lock')):continue
 b=subprocess.check_output(['git','show',rec['source_revision']+':'+p],cwd=R)
 assert hashlib.sha256(b).hexdigest()==h,p
# Extraction used the same executable reference: only Kani-only contracts differ.
raw=subprocess.check_output(['git','show','1158d679a:tools/multiproof-cone-20261021/src/reference.rs'],cwd=R)
attrs=(T/'src/reference.rs').read_text()
stripped=('\n'.join(line for line in attrs.splitlines() if not line.startswith('#[cfg_attr(kani,'))+'\n').encode()
assert raw==stripped
ex=json.loads((E/'host/extraction/charon-5-inputs.json').read_text())
assert hashlib.sha256(raw).hexdigest()==ex['source_sha256']
pref=json.loads((E/'host/receipts/parser-charon-2/receipt.json').read_text())
assert pref['source_sha256']['tools/multiproof-cone-20261021/src/parser_reference.rs']==sha(T/'src/parser_reference.rs')
for namespace,directory in [('MultiproofConeRef','/tmp/codex-cx-multiproof-extraction'),('MultiproofParserRef','/tmp/codex-cx-parser-extraction')]:
 for name in ['Types','Funs']:
  assert sha(L/namespace/(name+'.lean'))==sha(Path(directory)/namespace/(name+'.lean'))
# All inherited Lean, shipped crates and sibling candidates remain read-only.
paths=subprocess.check_output(['git','diff','--name-status',BASE,'--','crates','docs/research/100bit-spend-path-20261013/lean-candidates'],cwd=R,text=True)
assert not paths,paths
changed=subprocess.check_output(['git','diff','--name-only',BASE,'--',str(L.relative_to(R))],cwd=R,text=True).splitlines()
for p in changed:
 exists=subprocess.run(['git','cat-file','-e',BASE+':'+p],cwd=R,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL).returncode==0
 assert not exists,('Existing Lean module changed',p)
result=dict(status='PASS: focused local facts and 18 P6 cuts; both whole cones remain open',source_revision=current['MultiproofConeFreeze']['source_revision'],lean_modules=len(current),successful_axiom_reports=sum(len(a['axioms']) for a in current.values()),standard_axioms=sorted(allowed),peak_rss_bytes=max(a['peak_rss_bytes'] for a in current.values()),swaps=0,rust_source_revision=rec['source_revision'],kani_roots=len(roots),kani_wall_seconds=rec['wall_seconds'],kani_peak_rss_kib=rec['peak_rss_kib'],shipped_sources_unchanged=True,sibling_candidates_unchanged=True,complete_parser_cone=False,complete_multiproof_cone=False,accepted_run_join_constructed=False,coherent_frozen_release_replay=False)
(E/'audit-result.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps(result,indent=2))

#!/usr/bin/env python3
"""Lift exact frozen items and generate owned references, never edit shipped files."""
from pathlib import Path
import hashlib, json, sys, subprocess
R=Path(__file__).resolve().parents[2]; T=Path(__file__).resolve().parent
E=R/'docs/research/100bit-spend-path-20261013/evidence/s7-kani-20261021'
V=R/'crates/aspis-r1-cost-probe/src/verifier.rs'; C=V.with_name('candidate.rs')
pins={}; items={}
def item(p, marker):
 s=p.read_text(); a=s.index(marker); b=s.index('{',a); depth=1; end=b+1
 while depth:
  depth+=(s[end]=='{')-(s[end]=='}'); end+=1
 out=s[a:end]; items[str(p.relative_to(R))+':'+marker]={'sha256':hashlib.sha256(out.encode()).hexdigest(),'start_line':s[:a].count('\n')+1,'end_line':s[:end].count('\n')+1}
 pins[str(p.relative_to(R))]=hashlib.sha256(p.read_bytes()).hexdigest()
 return out
header='''// Generated by generate.py: frozen items are byte-for-byte source slices.
extern crate alloc;
use alloc::vec::Vec;
use aspis_core::{field::{M31,QM31 as K,WideExact as E},circle::SecureCirclePoint,r0::domain};
use transport::Variant;
use weights::{field,QUARTER};
#[path="../../../crates/aspis-r1-cost-probe/src/transport.rs"] pub mod transport;
#[path="../../../crates/aspis-r1-cost-probe/src/fast_domain.rs"] pub mod fast_domain;
#[path="../../../crates/aspis-r1-cost-probe/src/fast_pairing.rs"] pub mod fast_pairing;
#[path="../../../crates/aspis-r1-cost-probe/src/fast_dots.rs"] pub mod fast_dots;
#[path="../../../crates/aspis-r1-cost-probe/src/trace.rs"] pub mod trace;
'''
frozen=header
for m in ['pub enum Error','pub enum Phase','pub struct Prepared','pub struct Accumulator','struct QueryGeometry','fn batch_prefix_products','impl QueryGeometry','fn circle_fold_with_inverses','fn line_fold_with_inverses','struct BatchedWeights','impl BatchedWeights','fn residue_limb_at','fn power_limb_at','fn update_residue_row','fn accumulate_with_node','fn basis_at','fn accumulated_weight_at','fn accumulate_batched_with_node']:
 frozen+=('#[derive(Debug,Clone,Copy,PartialEq,Eq)]\n' if m in ['pub enum Error','pub enum Phase'] else '')+item(V,m)+'\n\n'
frozen+='pub type Observer=Option<fn(Phase)>;\n'+item(V,'fn mark(')+'\n'
frozen+='mod weights { use super::*; pub const QUARTER:M31=M31(536870912);\n'+item(V.with_name('weights.rs'),'pub fn field(')+'\n}\n'
cs=V.with_name('compact.rs').read_text(); frozen+='mod compact {\n'+cs[cs.index('pub const MAGIC:'):cs.index('/// Bytes before the multiproof nodes')]+'}\n'
frozen+='pub mod verifier { pub const SEMANTIC_BYTES:usize=12903+29*32; }\n'
frozen+='mod candidate { use super::*; use compact::OPENING;\n'+item(C,'fn opening(')+'\n'+item(C,'fn query_values(')+'\n'+item(C,'fn query_loop(')+'''
pub(super) fn run(proof:&[u8],p:&Prepared,a:Accumulator,g:&[E;29],obs:Observer,geometry:&QueryGeometry,pending:BatchedWeights)->Result<(Accumulator,BatchedWeights),Error> { query_values(proof,p,a,g,obs,geometry,pending) }
}
'''
# Owned state removes only mutable-reference parameters. Loop order/trace remain literal.
owned=(T/'src/owned_accumulate.rs').read_text()
query=item(C,'fn query_values(').replace('fn query_values(', 'pub fn query_owned(')
query=query.replace('accumulate_batched_with_node(p, &mut a, node, folded, &mut pending);','let (a, pending) = accumulate_owned(p.rho, a, node, folded, pending);')
query=query.replace('let q = opening(proof, i);','let q = candidate::opening(proof, i);')
# Sibling privacy: keep query function in its own module, not an existing module.
query=query.replace('candidate::opening(proof, i)','opening(proof, i)')
loop='pub fn query_loop_owned(proof:&[u8],p:&Prepared,a:Accumulator,g:&[E;29],obs:Observer,geometry:&QueryGeometry,pending:BatchedWeights,end:usize)->Result<(Accumulator,BatchedWeights),Error> {\n    if a.next>=end {return Ok((a,pending));}\n    match query_owned(proof,p,a,g,obs,geometry,pending) {\n        Err(error)=>Err(error),\n        Ok((a,pending))=>query_loop_owned(proof,p,a,g,obs,geometry,pending,end)\n    }\n}\n'
owned+='\n'+item(C,'fn opening(')+'\n'+query+'\n'+loop
update=item(V,'fn update_residue_row')
a=update.index('        let old=');b=update.index('\n    }',a)
body=update[a:b]
a=update.index('*limb=');b=update.index(';',a)+1
fold=update[a:b]
steps='// Exact frozen loop-body fragments, wrapped for independent per-step Kani.\nfn frozen_update_limb(row:&mut [u64;4],power:K,basis:M31,j:usize) {\n    let limbs=[power.c0.a.0,power.c0.b.0,power.c1.a.0,power.c1.b.0];\n'+body+'\n}\nfn frozen_fold_limb(limb:&mut u64) {'+fold+'}\n'
group='core::array::from_fn(|j|flat_inverse[5*i+j])'
assert group in V.read_text()
steps+='fn frozen_group(flat_inverse:&[M31],i:usize)->[M31;5] {'+group+'}\n'
outputs={'src/frozen.rs':frozen,'src/owned.rs':owned,'src/frozen_steps.rs':steps}
for rel,s in outputs.items():
 p=T/rel
 if '--check' in sys.argv: assert p.read_text()==s, rel
 else:p.write_text(s)
for name in ['compact.rs','fast_dots.rs','fast_pairing.rs','fast_domain.rs','trace.rs','transport.rs']:
 p=V.with_name(name);pins[str(p.relative_to(R))]=hashlib.sha256(p.read_bytes()).hexdigest()
manifest={'reference_sources':{name:hashlib.sha256((T/name).read_bytes()).hexdigest() for name in ['src/owned_accumulate.rs','src/geometry_owned.rs','src/lib.rs','generate.py']},'frozen_revision':'b2727acd3abf79315d18b754a260f58f4b1c6326','worktree_base':'072b24afc','source_files':pins,'literal_items':items,'generated':{k:hashlib.sha256(v.encode()).hexdigest() for k,v in outputs.items()},'shipped_changes':subprocess.check_output(['git','diff','--name-only','072b24afc','--','crates','programs'],cwd=R,text=True).splitlines()}
assert not manifest['shipped_changes']
for path,sha in pins.items():
 assert hashlib.sha256(subprocess.check_output(['git','show','b2727acd3:'+path],cwd=R)).hexdigest()==sha,path
if '--check' in sys.argv: assert json.loads((E/'source-binding.json').read_text())==manifest
else:(E/'source-binding.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Frozen slices and owned references match; shipped source unchanged')

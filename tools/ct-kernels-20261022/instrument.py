#!/usr/bin/env python3
"""Restricted straight-line source translator; rejects unhandled control/index syntax.
Events mark entry and expression sites in the actual owned CT source, not a
handwritten expected trace. Primitive integer operations/comparisons are L2
atomic operations; their hardware lowering remains L3.
"""
from pathlib import Path
import re, hashlib, json
R=Path(__file__).resolve().parents[2]
s=(R/'crates/aspis-core/src/field/ct.rs').read_text()
s=re.sub(r'//[^\n]*','',s)
s=re.sub(r'#\[inline\(always\)\]','',s)
s=s.replace('use super::P;', 'use aspis_core::field::P;')
assert not re.search(r'\b(if|else|match|for|while|loop|unsafe|assert|return)\b|&&|\|\||\?|\[|\]|/|%',s)
# All calls must be explicitly reviewed integer primitives or owned kernels.
functions=re.findall(r'pub fn (\w+)\(',s)
assert functions==['subtract_p','reduce64','reduce128','add','sub','neg','is_zero']
assert set(re.findall(r'\b(\w+)\(',s)) <= set(functions+['wrapping_sub','wrapping_add'])
out=['// Generated by instrument.py from ct.rs; do not edit.','#[derive(PartialEq,Eq,Debug)] pub struct Trace {pub events:[u16;32],pub len:usize}', 'impl Trace {pub fn new()->Self {Self{events:[0;32],len:0}} pub fn event(&mut self,id:u16) {self.events[self.len]=id;self.len+=1;}}']
event=0
for line in s.splitlines():
 if not line.strip():continue
 if line.startswith('pub fn '):
  line=line.replace(') ->', ', trace: &mut Trace) ->')
  out.append(line);event+=1;out.append(f'    trace.event({event});');continue
 if line.strip() not in ['}'] and not line.startswith('use '):
  event+=1;out.append(f'    trace.event({event});')
  line=re.sub(r'subtract_p\(([^;]+)\)',r'subtract_p(\1, trace)',line)
 out.append(line)
result='\n'.join(out)+'\n'
(R/'tools/ct-kernels-20261022/instrumented.rs').write_text(result)
print(json.dumps(dict(source_sha256=hashlib.sha256((R/'crates/aspis-core/src/field/ct.rs').read_bytes()).hexdigest(),instrumented_sha256=hashlib.sha256(result.encode()).hexdigest(),events=event,functions=functions)))

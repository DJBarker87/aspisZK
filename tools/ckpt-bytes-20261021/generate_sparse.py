#!/usr/bin/env python3
"""Emit six sparse wide intervals, never concrete checkpoint buffers."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[2]
LEAN = ROOT / 'docs/research/100bit-spend-path-20261013/lean'
source = (LEAN / 'OraclePortCkptAbi2Extracted/Funs.lean').read_text().split('def body_byte',1)[1]
thresholds = [int(x) for x in re.findall(r'if i < (\d+)#usize',source)]
assert thresholds == [8,16,48,80,112,176,304,320,408,568,632,664,696,712]
fields = [
    ('gamma',176,'p.gamma'),('kappa',208,'p.kappa'),
    ('alpha0',240,"p.alpha.val[0]'(by simp [p.alpha.property])"),
    ('alpha1',272,"p.alpha.val[1]'(by simp [p.alpha.property])"),
    ('claim',632,'p.claim'),('rhs',664,'a.rhs')]
text = '''-- Generated by tools/ckpt-bytes-20261021/generate_sparse.py; --check validates it.
import CheckpointBytesBodyArithmetic
import CheckpointBytesEC5

set_option autoImplicit false
namespace AspisR1.CheckpointBytesSparseE
open Aeneas Aeneas.Std Result
open OraclePortCkptAbi2Extracted OraclePortCkptAbi4Decode OraclePortCkptAbi5Codec
open CheckpointBytesBodyArithmetic CheckpointBytesEC5
attribute [local irreducible] body_byte e_byte
abbrev Prepared := aspis_r1_cost_probe.verifier.Prepared
abbrev Accumulator := aspis_r1_cost_probe.verifier.Accumulator
'''
for name,start,field in fields:
    reached = next(t for t in thresholds if t >= start+32)
    guards = thresholds[:thresholds.index(reached)+1]
    text += f'''
/-- The {name} interval is selected symbolically; field bytes stay folded. -/
theorem {name}_dispatch (p : Prepared) (a : Accumulator) (hp hu : Array U8 32#usize)
    (i : Usize) (bound : i.val < 32) :
    body_byte p a hp hu (Usize.ofNat ({start}+i.val) (by scalar_tac)) =
      e_byte ({field}) i := by
  let at1 := Usize.ofNat ({start}+i.val) (by scalar_tac)
  have value : at1.val = {start}+i.val := by simp [at1]
'''
    for t in guards:
        text += f'  have h{t} : {"" if t==reached else "¬ "}at1 < {t}#usize := by scalar_tac\n'
    text += '  change body_byte p a hp hu at1 = _\n'
    text += '  simp only [body_byte,' + ','.join(f'if_{"pos" if t==reached else "neg"} h{t}' for t in guards)+']\n'
    if start < 304:
        text += f'  have quotient : ({start}+i.val-176)/32 = {(start-176)//32} := by omega\n'
        text += f'  have remainder : ({start}+i.val-176)%32 = i.val := by omega\n'
    text += '''  simp (disch := scalar_tac) [Array.index_usize,Array.make,
    sub_exact,div_exact,rem_exact,value'''
    if start < 304:
        text += ',quotient,remainder'
    text += ',Nat.div_eq_of_lt bound,Nat.mod_eq_of_lt bound]\n'
    text += f'''
theorem {name}_c5 (p : Prepared) (a : Accumulator) (hp hu : Array U8 32#usize)
    (canonical : CanonicalWide ({field})) (i : Usize) (bound : i.val < 32) :
    ∃ v, body_byte p a hp hu (Usize.ofNat ({start}+i.val) (by scalar_tac)) = ok v ∧
      (OraclePortCheckpointAbiC5.encodeE (exactE ({field}) canonical))[i.val]? =
        some (AspisV8R19.SqueezeOracleBridge.decodeByte v) := by
  rw [{name}_dispatch p a hp hu i bound]
  exact e_byte_c5 _ canonical i bound

#print axioms {name}_dispatch
#print axioms {name}_c5
'''
text += 'end AspisR1.CheckpointBytesSparseE\n'
target = LEAN / 'CheckpointBytesSparseE.lean'
p = argparse.ArgumentParser(); p.add_argument('--check',action='store_true'); args=p.parse_args()
if args.check:
    assert target.read_text() == text, 'generated sparse intervals differ'
    print('six sparse wide intervals match source thresholds and generator')
else:
    target.write_text(text)

#!/usr/bin/env python3
"""Generate bounded sparse K section proofs, not buffer reductions."""
from pathlib import Path
import argparse,re
ROOT=Path(__file__).resolve().parents[2]
LEAN=ROOT/'docs/research/100bit-spend-path-20261013/lean'
source=(LEAN/'OraclePortCkptAbi2Extracted/Funs.lean').read_text().split('def body_byte',1)[1]
thresholds=[int(x) for x in re.findall(r'if i < (\d+)#usize',source)]
assert thresholds==[8,16,48,80,112,176,304,320,408,568,632,664,696,712]
fields=[('rho',304,304,'p.rho',0),('power',696,696,'a.power',0),
 ('semantic',408,408,"p.semantic_alpha.val[j.val]'(by simpa [p.semantic_alpha.property] using j.isLt)",10)]
for j in range(4):
 point=f"p.z.val[{j//2}]'(by simp [p.z.property])"
 fields.append((f'coordinate{j}',568+16*j,568,f'({point}).{"x" if j%2==0 else "y"}',0))
fields.append(('weight',712,712,"a.weights.val[j.val]'(by rw [size]; exact j.isLt)",64))
s='''-- Generated by tools/ckpt-bytes-20261021/generate_sparse_k.py; supports --check.
import CheckpointBytesBodyArithmetic
import CheckpointBytesK

set_option autoImplicit false
namespace AspisR1.CheckpointBytesSparseK
open Aeneas Aeneas.Std Result
open OraclePortCkptAbi2Extracted OraclePortCkptAbi4Decode OraclePortCkptAbi5Codec
open CheckpointBytesBodyArithmetic CheckpointBytesK
attribute [local irreducible] body_byte k_byte
abbrev Prepared := aspis_r1_cost_probe.verifier.Prepared
abbrev Accumulator := aspis_r1_cost_probe.verifier.Accumulator
'''
for name,start,base,field,n in fields:
 extent=start+(16*n if n else 16)
 reached=next((t for t in thresholds if t>=extent),None)
 guards=thresholds[:thresholds.index(reached)+1] if reached else thresholds
 extra=(' (size : a.weights.val.length = 64)' if name=='weight' else '')+(f' (j : Fin {n})' if n else '')
 expr=f'{start}'+('+16*j.val' if n else '')+'+i.val'
 s+=f'''
theorem {name}_dispatch (p : Prepared) (a : Accumulator) (hp hu : Array U8 32#usize)
    {extra} (i : Usize) (bound : i.val < 16) :
    body_byte p a hp hu (Usize.ofNat ({expr}) (by {'have := j.isLt; ' if n else ''}scalar_tac)) =
      k_byte ({field}) i := by
'''
 if n:s+='  have indexBound := j.isLt\n'
 s+=f'  let at1 := Usize.ofNat ({expr}) (by scalar_tac)\n  have value : at1.val = {expr} := by simp [at1]\n'
 for t in guards:s+=f'  have h{t} : {"" if t==reached else "¬ "}at1 < {t}#usize := by scalar_tac\n'
 s+='  change body_byte p a hp hu at1 = _\n'
 s+='  simp only [body_byte,'+','.join(f'if_{"pos" if t==reached else "neg"} h{t}' for t in guards)+']\n'
 if name not in ('rho','power'):
  s+=f'  have quotient : ({expr}-{base})/16 = '+('j.val' if n else str((start-base)//16))+' := by omega\n'
  s+=f'  have remainder : ({expr}-{base})%16 = i.val := by omega\n'
 opts=['Array.index_usize','Array.make','sub_exact','div_exact','rem_exact','value','Nat.div_eq_of_lt bound','Nat.mod_eq_of_lt bound']
 if name not in ('rho','power'):opts+=['quotient','remainder']
 if n==10:opts+=['p.semantic_alpha.property']
 if name=='weight':opts+=['alloc.vec.Vec.index','core.slice.index.SliceIndexUsizeSlice','Slice.index_usize','size']
 s+='  simp (disch := scalar_tac) ['+','.join(opts)+']\n'
 params=' '.join(['size'] if name=='weight' else [])+(' j' if n else '')
 s+=f'''
theorem {name}_c5 (p : Prepared) (a : Accumulator) (hp hu : Array U8 32#usize)
    {extra} (canonical : Canonical ({field})) (i : Usize) (bound : i.val < 16) :
    ∃ v, body_byte p a hp hu (Usize.ofNat ({expr}) (by {'have := j.isLt; ' if n else ''}scalar_tac)) = ok v ∧
      (OraclePortCheckpointAbiC5.encodeK (exactK ({field}) canonical))[i.val]? =
        some (AspisV8R19.SqueezeOracleBridge.decodeByte v) := by
  rw [{name}_dispatch p a hp hu {params} i bound]
  exact k_byte_c5 _ canonical i bound

#print axioms {name}_dispatch
#print axioms {name}_c5
'''
s+='end AspisR1.CheckpointBytesSparseK\n'
target=LEAN/'CheckpointBytesSparseK.lean'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
if args.check:
 assert target.read_text()==s
 print('eight sparse K sections match generator and source thresholds')
else:target.write_text(s)

"""Generate source-shaped checker steps, with separately checked erasure.

Does not edit extraction/shipped code or execute a build. The checker body's
bind sequence is read from CertCheckExtracted; recursion is isolated into a
step and its progress theorem. Native/challenge correspondence stays open.
"""
from pathlib import Path
import re,sys
CHECK="--check" in sys.argv
def emit(path,text):
    if CHECK:
        if not path.exists() or path.read_text()!=text: raise SystemExit(f"stale generated file: {path}")
    else: path.write_text(text)
ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'docs/research/v8-r0-zk-20261009/lean/R1Z'
SRC=(BASE/'CertCheckExtracted.lean').read_text()
# name, module, fixed parameter names, counter, bound, new flag, increment
ROWS=[
 ('id_row_ok','IdentityRow','c co i w','j','w','ok1 && (i5 = i6)','j1'),
 ('ech_row_ok','EchelonRow','e n lst a r','b','r','ok1 && (i5 = i6)','b1'),
 ('perm_left_ok','PermutationLeft','lst tag n','x','n','ok1 && (i3 = i4)','x1'),
 ('perm_right_ok','PermutationRight','lst tag n','c','n','ok1 && (i3 = i4)','c1'),
]
for number,(fn,mod,args,counter,bound,flag,inc) in enumerate(ROWS,10):
    start=SRC.index('def '+fn+'_loop\n')
    end=SRC.index('partial_fixpoint',start)
    text=SRC[start:end]
    header,body=text.split('  := do\n',1)
    params=header[header.index('\n'):header.index(' :\n  Result')]
    # Preserve fixed argument groups and separate the last flag/index groups.
    pos=params.index('(ok1 : Bool)')
    fixed=params[:pos].rstrip()
    sequence=body.split('  then\n',1)[1].split('    '+fn+'_loop',1)[0]
    lines=sequence.splitlines()
    recorded=[]; binds=[]
    for line in lines:
        m=re.fullmatch(r'    let (\w+) ← (.*)',line)
        if not m: raise ValueError(line)
        var,expr=m.groups();binds.append(var)
        if expr.startswith('lift '):
            value=expr[6:-1] if expr.startswith('lift (') else expr[5:]
            if 'cast_fromBool' in expr:
                cond=expr[expr.index('(',expr.index('cast_fromBool'))+1:-2]
                recorded.append(f'  let {var} ← operation (.guard {number} 0 0 ({cond})) (ok ({value}))')
            else: recorded.append(f'  let {var} := {value}')
        elif expr.startswith('Slice.index_usize '):
            arr,idx=expr.removeprefix('Slice.index_usize ').split()
            array_id=args.split().index(arr)
            recorded.append(f'  let {var} ← operation (.index {array_id} {idx}.val) ({expr})')
        else:
            lhs,op,rhs=expr.split()
            constructor={'+':'add','*':'mul','%':'rem','-':'guard'}[op]
            if op=='-': event=f'.guard {number} {lhs}.val {rhs}.val true'
            else: event=f'.{constructor} {lhs}.val {rhs}.val'
            if '#' in rhs: event=event.replace(rhs+'.val',f'({rhs}).val')
            recorded.append(f'  let {var} ← operation ({event}) ({expr})')
    step='\n'.join(line[2:] for line in lines)
    cmp=flag.removeprefix('ok1 && ')
    recorded.append(f'  operation (.guard {number} 0 0 {cmp}) (ok ({flag},{inc}))')
    paramsAll=f'{fixed} (ok1 : Bool) ({counter} : Usize)'
    typed=f'{paramsAll} :'
    proof=f'''import R1Z.PV_L2_F6FlagLoop

/-! Source-shaped {fn}: retain every checked arithmetic/index prefix.
Generated by make-checker-records.py; erasure checks the actual extraction. -/
set_option autoImplicit false
namespace R1Z.PV_L2_F6{mod}Step
open Aeneas Aeneas.Std Result R1CertCheck R1Z.CertCheck R1Z.PV_L2_Record

def step {typed} Result (Bool × Usize) := do
{step}
  ok ({flag},{inc})

def recorded {typed} Recorded (Bool × Usize) := do
{chr(10).join(recorded)}

theorem recorded_erases {paramsAll} :
    (recorded {args} ok1 {counter}).value = step {args} ok1 {counter} := by
  simp only [recorded,step,operation_bind_value,operation_value,lift,bind_tc_ok]

theorem unroll {paramsAll} :
    {fn}_loop {args} ok1 {counter} =
      if {counter}<{bound} then (do
        let (flag1,index1) ← step {args} ok1 {counter}
        {fn}_loop {args} flag1 index1) else ok ok1 := by
  rw [{fn}_loop]
  split
  · simp only [step,bind_assoc_eq,bind_tc_ok]
  · rfl

theorem increment {paramsAll} (after : Bool × Usize)
    (success : step {args} ok1 {counter} = ok after) : after.2.val={counter}.val+1 := by
  unfold step at success
'''
    for var in binds: proof+=f'  obtain ⟨{var},h{var},success⟩ := bind_eq_ok success\n'
    proof+=f'''  have he := ok_inj success
  rw [←he]
  simpa only [show (1#usize).val=1 from rfl] using add_ok h{inc}

#print axioms recorded_erases
#print axioms unroll
#print axioms increment
end R1Z.PV_L2_F6{mod}Step
'''
    emit(BASE/f'PV_L2_F6{mod}Step.lean',proof)
    full=f'''import R1Z.PV_L2_F6{mod}Step
set_option autoImplicit false
namespace R1Z.PV_L2_F6{mod}
open Aeneas Aeneas.Std Result R1CertCheck R1Z.PV_L2_Record
open R1Z.PV_L2_F6{mod}Step

def recorded {fixed} : Recorded Bool :=
  PV_L2_F6FlagLoop.loop {number} (PV_L2_F6{mod}Step.recorded {args}) {bound} {bound}.val true 0#usize

theorem erases {fixed} :
    (recorded {args}).value = {fn} {args} := by
  unfold recorded
  apply PV_L2_F6FlagLoop.erases {number} (PV_L2_F6{mod}Step.recorded {args}) {bound}
    ({fn}_loop {args})
  · intro flag index
    rw [PV_L2_F6{mod}Step.recorded_erases]
    exact unroll {args} flag index
  · intro flag index after hs
    rw [PV_L2_F6{mod}Step.recorded_erases] at hs
    exact increment {args} flag index after hs
  · omega

#print axioms erases
end R1Z.PV_L2_F6{mod}
'''
    emit(BASE/f'PV_L2_F6{mod}.lean',full)
print('generated',len(ROWS)*2,'focused modules')


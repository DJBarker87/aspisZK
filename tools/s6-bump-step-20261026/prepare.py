#!/usr/bin/env python3
"""Copy complete pinned SDK allocator declarations, with no semantic edits."""
from pathlib import Path
import hashlib
import json
import subprocess
import sys
import tarfile

R = Path(__file__).resolve().parents[2]
D = Path(__file__).resolve().parent
O = Path(sys.argv[1]).resolve()
O.mkdir()  # Never overwrite an existing build workspace.
revision = '4bb3b3f51e16b4525f1d10336e2b0bcbbd775387'
checksum = '32ce041b1a0ed275290a5008ee1a4a6c48f5054c8a3d78d313c08958a06aedbd'
archive = Path.home()/'.cargo/registry/cache/index.crates.io-1949cf8c6b5b557f/solana-program-entrypoint-2.3.0.crate'
sha = lambda b: hashlib.sha256(b).hexdigest()
assert sha(archive.read_bytes()) == checksum
with tarfile.open(archive) as package:
    original = package.extractfile('solana-program-entrypoint-2.3.0/src/lib.rs').read()
source = original.decode()
begin = source.index('pub struct BumpAllocator {')
end = source.index('/// `assert_eq(std::mem::align_of::<u128>()', begin)
copied = source[begin:end]
assert copied.count('unsafe fn alloc(') == 1
assert copied.count('unsafe fn dealloc(') == 1
lock = subprocess.check_output(['git', 'show', revision+':Cargo.lock'], cwd=R)
assert ('name = "solana-program-entrypoint"\nversion = "2.3.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "'+checksum+'"').encode() in lock
(O/'harness/src').mkdir(parents=True)
(O/'harness/src/shipped.rs').write_text('use core::{alloc::Layout,mem::size_of,ptr::null_mut};\n\n'+copied)
(O/'harness/src/lib.rs').write_bytes((D/'proof.rs').read_bytes())
(O/'harness/Cargo.toml').write_text('[package]\nname="s6-bump-step"\nversion="0.1.0"\nedition="2021"\n[workspace]\n')
(O/'harness/Cargo.lock').write_text('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "s6-bump-step"\nversion = "0.1.0"\n')
(O/'registry-pins.json').write_text('{}\n')
(O/'sdk-original.rs').write_bytes(original)
(O/'binding.json').write_text(json.dumps({
    'schema': 'focused-extractor-proof-packet-v1', 'release_revision': revision,
    'release_lock_sha256': sha(lock), 'registry_checksum': checksum,
    'sdk_source_sha256': sha(original), 'copied_declarations_sha256': sha(copied.encode()),
    'copied_begin_marker': 'pub struct BumpAllocator {',
    'copied_end_marker': '/// `assert_eq(std::mem::align_of::<u128>()',
    'semantic_edits': [], 'whole_caller_closed': False,
    'scope': 'One actual SDK allocator step/dealloc on a valid local262144-byte arena, arbitrary cursor/size and align1/2/4/8; no Box/global-allocator dispatch or release heap-entry association.'
}, indent=2)+'\n')
print(str(O))

#!/usr/bin/env python3
"""NPP_: generate NPP_ComputableModel.lean (stage A for I.entry, tx1Value, tx2Value, the TX1 producer).
Usage: python3 -I NPP_gen_model.py <repo-evidence-dir> <out-dir>
cand = NPO_ID_DEPENDENTS ∪ the noncomputable closure of the four roots (NPO_L035), minus
Classical.*, Exists.* and List.flatten; leaves = the classical and no_ir_other constants of that
closure. Copies already made by NPP_ComputableSdk are reused."""
import json, sys, os
ev, out = sys.argv[1], sys.argv[2]
dep = json.load(open(os.path.join(ev, 'host-ids-20261110/NPO_ID_DEPENDENTS.json')))['dependents']
nc = json.load(open(os.path.join(ev, 'host-ids-20261110/NPO_L035/NPO_NONCOMPUTABLE.json')))
rows = {r['n']: r for r in nc['constants']}
roots = ['NNH_ReturnsBundle.tx1Value', 'NNH_ReturnsBundle.tx2Value', 'AspisR1.NNG_TotalProducer345.producer',
         'AspisR1.NNH_Run6Installed.implementation']
if len(sys.argv) > 3: roots = sys.argv[3].split(',')
nocode = json.load(open(os.path.join(out, 'NPP_L063/NPP_NOCODE.json')))
seen = []
for root in roots:
    st = [root]
    while st:
        n = st.pop()
        if n in seen or n not in rows: continue
        seen.append(n); st += rows[n]['noncomputable_deps']
skip = lambda n: n.startswith('Classical.') or n.startswith('Exists.') or n == 'List.flatten'
closure = [n for n in seen if not skip(n)]
leaves = [n for n in closure if rows[n]['cause'] in ('classical', 'no_ir_other')]
# the compiler's view (NPP_L063): every definition without code in the roots' value closure
ncset = {r['n'] for r in nocode}
for r in nocode:
    if r['n'] not in closure: closure.append(r['n'])
    deps_in = False
    if r['n'] not in leaves: leaves.append(r['n'])   # every no-code definition is copied
iddep = sorted(d['name'] for d in dep)
cand = sorted(set(iddep) | set(closure))
json.dump({'roots': roots, 'closure': closure, 'leaves': leaves, 'cand_count': len(cand)},
          open(os.path.join(out, 'NPP_MODEL_INPUTS.json'), 'w'), indent=1)
def lit(xs): return '#[' + ',\n  '.join(json.dumps(x) for x in xs) + ']'
lib = open(os.path.join(out, 'NPP_src/NPP_Lib.lean')).read().replace('import Lean\n', '').replace('import Aeneas\n', '')
lib = lib.replace('namespace NPP\n', 'namespace NPP2\n', 1).replace('\nend NPP\n', '\nend NPP2\n')
lib = lib.replace('``NPP.', '``NPP2.')
names = f'''
namespace NPP2.Inputs
def cand : Array String := {lit(cand)}
def leaves : Array String := {lit(leaves)}
def idDep : Array String := {lit(iddep)}
def roots : Array String := {lit(roots)}
def toSet (xs : Array String) : NameSet := xs.foldl (fun s x => s.insert x.toName) {{}}
def ids : Std.HashMap Name Name := Std.HashMap.ofList [
  (`AspisR1.CPH_Program.verifier, `NPO_DeployedIds.verifierNov),
  (`NHJ_IdPacket.poolDefault, `NPO_DeployedIds.poolNov),
  (`NHJ_IdPacket.registryDefault, `NPO_DeployedIds.registryNov)]
end NPP2.Inputs
'''
hdr = '''import Lean
import NPP_ComputableSdk
import NPP_Refine
import NNH_ReturnsBundle
import NNG_TotalProducer345
import NNH_Run6Installed
set_option autoImplicit false
set_option maxHeartbeats 0
/-! NPP_ stage A2 (Stream A, gate row 5, step 3; generated by NPP_gen_model.py). Computable copies
`NPP_C.*` of the cones of I.entry, tx1Value, tx2Value and the TX1 producer, reusing the
NPP_ComputableSdk copies; refinement library NPP2 (= NPP_Lib with total-Result choice sites).
Target not yet established. -/
'''
derive = '''
/-! Structural `DecidableEq` for the structure carriers of the remaining equality sites (the
QM31 carrier `LPi_FieldValues.NQ` under the canonical-QM31 subtype, and the circle point), by the
standard deriving handler through `NPP.deriveDecEq` (NPP_ComputableSdk). New computable instances
only. -/
open Lean Elab Command Meta in
def NPP2.headStructure (n : Name) : CommandElabM Name := liftTermElabM do
  let some ci := (← getEnv).find? n | throwError "unknown {n}"
  let t ← match ci with
    | .defnInfo d => pure d.value
    | _ => pure (mkConst n (ci.levelParams.map Level.param))
  let t ← whnf t
  let t := if t.isAppOfArity ``Subtype 2 then t.appFn!.appArg! else t
  let t ← whnf t
  let some h := t.getAppFn.constName? | throwError "no head for {n}"
  return h
open Lean Elab Command in
run_cmd do
  for n in [`AspisR1.LPi_FieldValues.NQ, `AspisR1PublicPreparation.aspis_core.circle.SecureCirclePoint] do
    let h ← NPP2.headStructure n
    NPP.deriveDecEq h

/-! Computable `DecidableEq` for the Aeneas carriers that are definitions over a Subtype (the
instance search cannot see through them): the Subtype instance, re-exposed. -/
instance NPP2.decEqArray {α : Type} [DecidableEq α] {n : Aeneas.Std.Usize} : DecidableEq (Aeneas.Std.Array α n) :=
  inferInstanceAs (DecidableEq {l : List α // l.length = n.val})
instance NPP2.decEqSlice {α : Type} [DecidableEq α] : DecidableEq (Aeneas.Std.Slice α) :=
  inferInstanceAs (DecidableEq {l : List α // l.length ≤ Aeneas.Std.Usize.max})
instance NPP2.decEqVec {α : Type} [DecidableEq α] : DecidableEq (Aeneas.Std.alloc.vec.Vec α) :=
  inferInstanceAs (DecidableEq {l : List α // l.length ≤ Aeneas.Std.Usize.max})

/-! Phase 0: for every `Classical.propDecidable (a = b)` site of a leaf whose carrier has no
structural instance, derive `DecidableEq` for the carrier's inductive head (recursively through
constructor argument types), by the standard deriving handler. -/
open Lean Elab Command Meta in
partial def NPP2.deriveRec (T : Name) (depth : Nat := 0) : CommandElabM Unit := do
  if depth > 12 then return
  let env ← getEnv
  let some (.inductInfo ii) := env.find? T | return
  -- parameter-free project inductives only (core/library families keep their own instances)
  if ii.numParams != 0 || ii.numIndices != 0 || ii.isRec || T.getRoot == `Option || T.getRoot == `Subtype then return
  let has ← liftTermElabM do
    let some ci := env.find? T | return true
    forallTelescope ci.type fun xs _ => do
      let ty := mkAppN (mkConst T (ci.levelParams.map Level.param)) xs
      try return (← synthInstance? (← mkAppM ``DecidableEq #[ty])).isSome catch _ => return true
  if has then return
  for c in ii.ctors do
    let some cc := env.find? c | continue
    let heads ← liftTermElabM <| forallTelescope cc.type fun xs _ => do
      let mut hs : Array Name := #[]
      for x in xs do
        let t ← inferType x
        -- every inductive constant in the argument type (element types of Aeneas arrays included)
        for c in (t.getUsedConstants ++ (← whnf t).getUsedConstants) do
          if let some (.inductInfo _) := (← getEnv).find? c then
            if !hs.contains c then hs := hs.push c
      return hs
    for h in heads do
      if h != T then NPP2.deriveRec h (depth + 1)
  let saved := (← get).messages
  let envSaved ← getEnv
  try
    elabCommand (← `(deriving instance DecidableEq for $(mkIdent T)))
    if (← get).messages.hasErrors && !saved.hasErrors then
      let errs ← ((← get).messages.toList.filter (·.severity == .error)).mapM fun m => m.data.toString
      modify fun st => { st with messages := saved }
      setEnv envSaved
      let fields ← liftTermElabM do
        let mut out : Array String := #[]
        for c in ii.ctors do
          if let some cc := (← getEnv).find? c then
            out := out.push (toString (← ppExpr cc.type))
        return out
      NPP2.log <| Json.mkObj [("derive_failed", toJson T.toString), ("error", toJson ((String.intercalate " | " errs).take 400)), ("ctor_types", toJson fields)]
    else
      NPP2.log <| Json.mkObj [("derive_DecidableEq", toJson T.toString)]
  catch e => NPP2.log <| Json.mkObj [("derive_failed", toJson T.toString), ("error", toJson ((← e.toMessageData.toString).take 300).toString)]

open Lean Elab Command Meta in
run_cmd do
  let carriers ← liftTermElabM do
    let r ← IO.mkRef (#[] : Array Name)
    for n in NPP2.Inputs.leaves do
      let some ci := (← getEnv).find? n.toName | continue
      let some v := ci.value? (allowOpaque := true) | continue
      let _ ← transform v (post := fun e => do
        if e.isAppOfArity ``Classical.propDecidable 1 then
          if let some (ty, _, _) := e.appArg!.eq? then
            if (← NPP2.findInstTy (← getEnv) (mkApp (mkConst ``Decidable) e.appArg!)).isNone then
              let t ← whnf ty
              let t := if t.isAppOfArity ``Subtype 2 then t.appFn!.appArg! else t
              if let some h := (← whnf t).getAppFn.constName? then
                if !(← r.get).contains h then r.modify (·.push h)
        return .done e)
    r.get
  NPP2.log <| Json.mkObj [("phase0_carriers", toJson (carriers.map toString))]
  for h in carriers do NPP2.deriveRec h
'''
body = '''
open Lean Meta in
run_meta do
  let mut allCopied : Array Name := #[]
  let mut allEqs : Array Name := #[]
  for r in NPP2.Inputs.roots do
    let (copied, eqs) ← NPP2.stageA r.toName (NPP2.Inputs.toSet NPP2.Inputs.cand)
      (NPP2.Inputs.toSet NPP2.Inputs.leaves) NPP2.Inputs.ids (NPP2.Inputs.toSet NPP2.Inputs.idDep) `NPP_C
    allCopied := allCopied ++ copied; allEqs := allEqs ++ eqs
  NPP2.log <| Json.mkObj [("event","stageA2"),("copied", toJson allCopied.size),("eqs", toJson allEqs.size)]
  for e in allEqs do
    let ax ← collectAxioms e
    NPP2.log <| Json.mkObj [("axioms", toJson e.toString), ("value", toJson (ax.map toString))]
  for c in allCopied do
    NPP2.log <| Json.mkObj [("copy", toJson c.toString), ("noncomputable", toJson (isNoncomputable (← getEnv) c)),
      ("ir", toJson ((Lean.IR.findEnvDecl (← getEnv) c).isSome))]
'''
open(os.path.join(out, 'NPP_src/' + (sys.argv[4] if len(sys.argv) > 4 else 'NPP_ComputableModel') + '.lean'), 'w').write(hdr + lib + names + derive + body)
print(len(cand), len(leaves), len(closure))

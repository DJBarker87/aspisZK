"""Generate exact504 metadata checks from the accepted six raw calls."""
import hashlib,json,pathlib,sys
P=pathlib.Path('evidence/pv-lib-20261107/lane-A/session6/CELL504_SPECIALIZATIONS.json')
O=pathlib.Path('lean/PV_LIB_A_CellSetMetadata.lean')
def data(x):
 if x is None:return '.null'
 if isinstance(x,bool):return '.boolean '+str(x).lower()
 if isinstance(x,int):return '.number '+str(x)
 if isinstance(x,str):return '.atom '+json.dumps(x,ensure_ascii=False)
 if isinstance(x,list):return '.array ['+','.join(data(y) for y in x)+']'
 if isinstance(x,dict):return '.object ['+','.join('('+json.dumps(k)+','+data(v)+')'for k,v in x.items())+']'
 raise TypeError(x)
s='''import PV_LIB_A_CellSetBegin
set_option autoImplicit false
noncomputable section
namespace PV_LIB_A_CellSetMetadata
open PV_STX2_Syntax PV_LIB_A_CellSetBegin
/- Generated by session7/generate-cell-fixtures.py from the retained exact calls.
Only finite metadata is reduced; no concrete execution trace is normalized. -/
'''
roots=[]
for r in json.loads(P.read_text())['sites']:
 n=r['caller'].split('f')[-1];fn=r['call']['func'];g=fn['Regular']['generics']
 s+='def fn'+n+' : Data := '+data(fn)+'\n'
 s+='def d'+n+' : Destructor := ⟨'+data(g['types'][0])+','+data(g['trait_refs'][0])+'⟩\n'
 for name,stmt in [('metadata'+n,'destructor fn'+n+' = some d'+n),('trivial'+n,'trivial d'+n+' = '+str(n in ['417','437','629']).lower())]:
  s+='theorem '+name+' : '+stmt+' := rfl\n#print axioms '+name+'\n';roots.append('PV_LIB_A_CellSetMetadata.'+name)
s+='end PV_LIB_A_CellSetMetadata\n'
if '--check' in sys.argv:assert O.read_text()==s
else:O.write_text(s)
manifest=dict(input=str(P),sha256=hashlib.sha256(P.read_bytes()).hexdigest(),generated=str(O),source_sha256=hashlib.sha256(s.encode()).hexdigest(),roots=roots)
pathlib.Path('evidence/pv-lib-20261107/lane-A/session7/CELL_METADATA.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Checked six exact504 metadata/destructor bindings'if '--check'in sys.argv else 'Generated six exact504 metadata/destructor bindings')

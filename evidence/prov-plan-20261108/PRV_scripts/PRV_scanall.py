import json,re,sys,subprocess,hashlib,collections
S=sys.argv[1]
paths=collections.defaultdict(list)
for l in open(f"{S}/all_lean.tsv"):
    h,p=l.rstrip('\n').split('\t'); paths[h].append(p)
ids=list(paths)
p=subprocess.Popen(['git','cat-file','--batch'],stdin=subprocess.PIPE,stdout=subprocess.PIPE)
import threading
def feed():
    for i in ids: p.stdin.write((i+'\n').encode())
    p.stdin.close()
threading.Thread(target=feed).start()
cr=re.compile(r'/-.*?-/',re.S)
aen=re.compile(rb'AUTOMATICALLY GENERATED BY AENEAS')
ann=re.compile(rb"/--? \[[A-Za-z_0-9]+::[^\]]*\][^\n]*\n\s*Source: '")
out={}
for i in ids:
    hdr=p.stdout.readline().split()
    n=int(hdr[2]); data=p.stdout.read(n); p.stdout.read(1)
    sha=hashlib.sha256(data).hexdigest()
    head=data[:6000].decode('utf-8','replace')
    t=cr.sub('',head); imps=[];prelude=False
    for line in t.splitlines():
        s=line.split('--')[0].strip()
        if not s: continue
        if s=='prelude': prelude=True; continue
        if s.startswith('import '): imps+=s[7:].split(); continue
        break
    if not prelude: imps.append('Init')
    out[i]={'sha256':sha,'imports':sorted(set(imps)),'aeneas_header':bool(aen.search(data[:400])),'rust_annotations':len(ann.findall(data)),'bytes':n,'paths':paths[i]}
json.dump(out,open(f"{S}/lean_index.json","w"))
print(len(out), sum(1 for v in out.values() if v['aeneas_header']), sum(1 for v in out.values() if v['rust_annotations']))

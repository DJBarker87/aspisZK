#!/usr/bin/env python3
"""PCVL_gen_vtop.py: parametric-record statement for VTop_Stages tx2_common / tx2_authenticated against the fresh PCVJ_E002 emission.
The fresh emission's 23 external axioms become the fields of a structure `Ext` (a parameter, never declared as axioms); every fresh
definition that depends on an external gets a leading `(x : Ext)`. Statement (CONDITIONAL_ON_BINDING): for every gate `ops : Ops` whose
used fields are bound (Bound) to the fresh constants / Ext fields / fresh resume, fresh = gate ops. `bound_exists` shows Bound is satisfiable."""
import sys,re,json,importlib.util
sys.dont_write_bytecode=True
spec=importlib.util.spec_from_file_location('g','PCVL_gen_equalities.py');g=importlib.util.module_from_spec(spec);spec.loader.exec_module(g)
TAG=sys.argv[1] if len(sys.argv)>1 else 'l1'
OUT=f'PRVEq_VTop_{TAG}.lean'
FD='inputs/fresh_top/'
RENAMES=json.load(open('inputs/vtop_renames.json'))
def ren(t):
    for old,new in RENAMES:
        if old.endswith('.'): t=re.sub(r'(?<![\w.])'+re.escape(old)+r'(?=[\w.])',new,t)
        else: t=re.sub(r'(?<![\w.])'+re.escape(old)+r'(?![\w.])',new,t)
    return t
ftxt=open(FD+'Funs.lean').read()
etxt=g.uncomment(open(FD+'FunsExternal_Template.lean').read())
blocks=[b for b in g.parse_blocks(ftxt) if b['kind']=='decl']
names={b['name']:b for b in blocks}
# external signatures
def parse_ext_sigs(text):
    sigs={}
    for m in re.finditer(r'(?m)^\s*(?:@\[[^\]]*\]\s*)*axiom\s+(\S+)',text):
        n=m.group(1);i=m.end();j=text.find('\n\n',i);j=len(text) if j<0 else j
        sig=text[i:j];sig=re.split(r'\n/--|\n@\[',sig)[0].strip()
        sigs[n]=sig
    return sigs
sigs=parse_ext_sigs(etxt)
def split_binders(sig):
    d=0
    for k,c in enumerate(sig):
        if c in '([{': d+=1
        elif c in ')]}': d-=1
        elif c==':' and d==0 and not sig.startswith(':=',k): return sig[:k].strip(),sig[k+1:].strip()
    raise ValueError(sig)
clo=json.load(open('gen/vtop_closure.json'));D=clo['defs'];E=clo['ext']
def toks(b): return set(g.lean_ident_tokens(b['body']))
needs=set()
changed=True
while changed:
    changed=False
    for n in D:
        if n in needs: continue
        t=toks(names[n])
        if (t&set(E)) or (t&needs-{n}): needs.add(n);changed=True
mang=lambda n:n.replace('.','_')
field={e:mang(e) for e in E}
order=[b['name'] for b in blocks if b['name'] in D]
# Ext structure
out=[]
out.append(f'-- GENERATED by PCVL_gen_vtop.py (tag {TAG}). Fresh PCVJ_E002 emission (frozen 4bb3b3f, overflow ON) of tx2_common, tx2_authenticated and their closure,')
out.append('-- with the emission\'s 23 external axioms as fields of the parameter `Ext`. Gate: VTop_Stages (VTop_Model) tx2_common / tx2_authenticated over `ops : Ops`.')
out.append('-- RESULT CLASS: CONDITIONAL_ON_BINDING. Carrier names are mapped by inputs/vtop_renames.json (constructor prefixes only; the gate types are the abbrevs of VTop_Types).')
out.append('import Aeneas\nimport VTop_Model\nopen Aeneas Aeneas.Std Result ControlFlow Error\nset_option linter.dupNamespace false\nset_option linter.hashCommand false\nset_option linter.unusedVariables false\nset_option maxHeartbeats 1000000\nset_option maxRecDepth 2048\nnoncomputable section\n')
out.append('namespace VTop_Stages\nnamespace PRVFresh_VTop_'+TAG+'\n')
pre=open('inputs/vtop_prelude.lean').read() if __import__('os').path.exists('inputs/vtop_prelude.lean') else ''
out.append(pre)
out.append('structure Ext where')
for e in E:
    b,t=split_binders(' '.join(ren(sigs[e]).split()))
    ty=(f'∀ {b}, {t}' if b else t)
    out.append(f'  {field[e]} : {ty}')
out.append('')
tokre=re.compile(r'(?<![\w.\'])('+'|'.join(re.escape(n) for n in sorted(set(E)|needs,key=len,reverse=True))+r')(?![\w.\'])')
for n in order:
    b=names[n];t=g.strip_reg_attrs(b['text']) if hasattr(g,'strip_reg_attrs') else b['text']
    hm=re.search(r'(?<![\w.])(def|abbrev)(\s+)'+re.escape(n)+r'(?![\w.\'])',t)
    assert hm,n
    head,rest=t[:hm.end()],t[hm.end():]
    if n in needs: head+=' (x : Ext)'
    def sub(m):
        k=m.group(1)
        return 'x.'+field[k] if k in field else '('+k+' x)'
    rest=ren(tokre.sub(sub,rest))
    out.append(head+rest+'\n')
# Bound
B=json.load(open('inputs/vtop_bound.json'))   # list of [opfield, rhs]
out.append('structure Bound (ops : Ops) (x : Ext) : Prop where')
for k,(f,rhs) in enumerate(B): out.append(f'  h_{f} : @ops.{f} = {rhs}')
out.append('')
dummy=json.load(open('inputs/vtop_dummy.json'))  # {field: term}
out.append('def mkOps (x : Ext) : Ops where')
allf=[f'op{i}' for i in range(24)]+['unwrap32']
bm={f:rhs for f,rhs in B}
for f in allf: out.append(f'  {f} := {bm.get(f) or dummy[f]}')
out.append('')
out.append('theorem bound_exists (x : Ext) : Bound (mkOps x) x := ⟨'+', '.join('rfl' for _ in B)+'⟩\n#print axioms bound_exists\n')
common_args='{H : Type} (inst : aspis_core.digest.Digest32 H) (public_bytes proof checkpoint : Slice Std.U8) (hash : H) (obs : Option (verifier.Phase → Result Unit))'
allrw=', '.join(f'hb.h_{f}' for f,_ in B if f not in ('op3',) )
out.append(f'theorem eq_tx2_common (x : Ext) (ops : Ops) (hb : Bound ops x) {common_args} :\n  verifier.candidate.tx2_common x inst public_bytes proof checkpoint hash obs = VTop_Stages.verifier.candidate.tx2_common ops inst public_bytes proof checkpoint hash obs := by')
out.append('  unfold verifier.candidate.tx2_common VTop_Stages.verifier.candidate.tx2_common')
out.append('  rw ['+', '.join(f'hb.h_{f}' for f,_ in B if f!='op3')+']')
out.append('  all_goals rfl')
out.append('#print axioms eq_tx2_common\n')
out.append(f'theorem eq_tx2_authenticated (x : Ext) (ops : Ops) (hb : Bound ops x) {common_args} :\n  verifier.candidate.tx2_authenticated x inst public_bytes proof checkpoint hash obs = VTop_Stages.verifier.candidate.tx2_authenticated ops inst public_bytes proof checkpoint hash obs := by')
out.append('  unfold verifier.candidate.tx2_authenticated VTop_Stages.verifier.candidate.tx2_authenticated')
out.append('  rw [eq_tx2_common x ops hb, hb.h_op3, hb.h_op13]')
out.append('  all_goals rfl')
out.append('#print axioms eq_tx2_authenticated\n')
open(OUT,'w').write('\n'.join(out)+'\n')
json.dump(dict(needs_x=sorted(needs),order=order,ext_fields=field),open(f'gen/vtop_{TAG}.report.json','w'),indent=1)
print('wrote',OUT,len(order),'defs',len(needs),'with x')

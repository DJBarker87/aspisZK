#!/usr/bin/env python3
"""PCWQ_assemble.py OUT.lean : assemble the PRVEq file for RPz7_WAdm_Fissioned_Funs from the fresh frozen emission
(PCWQ_E003_emitted) and the hand-written proof parts gen/q1_proofs_*.lean.in. Fresh declarations are copied
verbatim (attributes rust_fun/rust_loop/rust_loop_body/rust_type removed, header options replaced); the only
change to emitted text is the `variable` line giving the external SharedAVec into_iter as a parameter."""
import re,sys,hashlib
sys.dont_write_bytecode=True
D='PCWQ_E003_emitted/raw/PCWQ_cpc/'
funs=open(D+'Funs.lean').read(); types=open(D+'Types.lean').read()
def cut(s,a,b=None):
    i=s.index(a); j=s.index(b,i) if b else len(s); return s[i:j]
def strip(s):
    s=re.sub(r'@\[rust_(fun|loop_body|loop|type)\b[^\]]*\]\n','',s)
    s=re.sub(r'@\[rust_(fun|loop_body|loop|type)\b[^\]]*\]\s*','',s)
    return s
fresh_types=cut(types,'/-- [aspis_r1_cost_probe::transport::Variant]','end PCWQ_cpc')
fresh_funs=cut(funs,'/-- [aspis_core::field::{aspis_core::field::M31}::to_le_bytes]','end PCWQ_cpc')
fresh_funs=fresh_funs.replace('PCWQ_cpc','PRVFresh_WAdm_q1')
EXT='SharedAVec.Insts.CoreIterTraitsCollectIntoIteratorSharedATIter.into_iter'
marker='/-- [aspis_r1_cost_probe::verifier::checkpoint]:\n'
assert marker in fresh_funs and EXT in fresh_funs
var=('section\n-- PCWQ parametrisation: the external <&Vec<T> as IntoIterator>::into_iter (no model in the Aeneas library) is the parameter SVI of checkpoint;\n'
     '-- the only change to the emitted text is the name of that constant inside checkpoint\n'
     'variable (SVI : {T : Type} → (A : Type) → alloc.vec.Vec T → Result (core.slice.iter.Iter T))\n\n')
i=fresh_funs.index(marker); fresh_funs=fresh_funs[:i]+var+fresh_funs[i:].replace(EXT,'SVI')
fresh_funs=fresh_funs.rstrip()+'\nend\n'
hdr='''-- GENERATED by PCWQ_assemble.py for gate module RPz7_WAdm_Fissioned_Funs (route 1: frozen op16 writer path = verifier::checkpoint).
-- fresh emission: PCWQ_E003 -> PRVFresh_WAdm_q1; frozen 4bb3b3f51e16b4525f1d10336e2b0bcbbd775387, ON configuration, cargo --jobs 4.
import Aeneas
import RPz7_WAdm_Fissioned_Funs
open Aeneas Aeneas.Std Result ControlFlow Error
set_option linter.dupNamespace false
set_option linter.hashCommand false
set_option linter.unusedVariables false
set_option maxHeartbeats 200000
set_option maxRecDepth 2048
noncomputable section

namespace WAdm_Fissioned
namespace PRVFresh_WAdm_q1

'''
parts=[open('gen/q1_proofs_%s.lean.in'%x).read() for x in 'abcde']
FR='PRVFresh_WAdm_q1'
out=hdr+strip(fresh_types)+'\n'+strip(fresh_funs)+''.join(parts)
out+='\nend PRVQ\nend WAdm_Fissioned\n\n'
for n in ['E_putK','E_putK_fun','E_wlb','E_body1','E_body2','E_body3','E_body5','E_loop1_fun','E_loop2_fun','E_loop3_fun','E_loop5_fun','hS_satisfiable','cs_S2','E_loop0','E_loop1','E_loop2','E_loop3','E_loop4','E_loop5','E_loop6','K_roots','K_early','K_tail','K_queries','K_semantic','K_coord','K_weights','checkpoint_eq','variantEquiv','preparedEquiv','accumulatorEquiv']:
    out+='#print axioms WAdm_Fissioned.PRVQ.%s\n'%n
open(sys.argv[1],'w').write(out)
print(sys.argv[1],len(out),hashlib.sha256(out.encode()).hexdigest())

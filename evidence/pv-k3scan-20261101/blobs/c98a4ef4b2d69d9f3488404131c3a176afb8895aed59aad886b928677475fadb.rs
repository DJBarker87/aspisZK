//! Generate D13's fixed permutation from the authoritative PF inventories.
//! Run with --check to audit the checked-in core pads and full-table KAT.
use aspis_statement::pool_v1::{
    pool_v1_pair_forest_copy_active_rows_v1, pool_v1_pair_forest_relation_free_mask_cells_v1,
};
use sha2::{Digest, Sha256};
use std::{fmt::Write, path::PathBuf};

fn main() {
    let active = pool_v1_pair_forest_copy_active_rows_v1().unwrap();
    let cells = pool_v1_pair_forest_relation_free_mask_cells_v1().unwrap();
    let legal = |r| (0..16).all(|c| cells.iter().any(|x| x.row == r && x.column == c));
    assert!(!active.contains(&1023) && legal(1023));
    // Exact order rule: v8-full-view-zk-20260912/tools/r16_basis_transport.rs:10–63.
    let pads: Vec<u16> = (0..1023)
        .filter(|r| !active.contains(r) && *r != 1014 && legal(*r))
        .take(89)
        .collect();
    assert_eq!(pads.len(), 89);
    let mut inverse = pads.clone();
    inverse.extend((0..1023).filter(|r| !pads.contains(r)));
    inverse.push(1023);
    let mut pi = [0u16; 1024];
    for (coefficient, &row) in inverse.iter().enumerate() {
        pi[usize::from(row)] = coefficient as u16;
    }
    let bytes: Vec<_> = pi.iter().flat_map(|r| r.to_le_bytes()).collect();
    let digest = format!("{:x}", Sha256::digest(&bytes));
    let mut source = String::from(
        "// Generated by aspis-statement/examples/r0_transport_inventory.rs; --check audits it.\n",
    );
    writeln!(source, "pub const PAD_ROWS: [u16; 89] = {pads:?};").unwrap();
    let kat = format!("{{\n  \"rule\": \"D13; historical r16_basis_transport.rs:10-63 order only\",\n  \"encoding\": \"pi[row], 1024 u16 little-endian entries\",\n  \"sha256\": \"{digest}\",\n  \"pads\": {pads:?},\n  \"pi\": {pi:?},\n  \"inverse\": {inverse:?}\n}}\n");
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    for (path, expected) in [
        ("crates/aspis-core/src/r0/transport_pads.rs", source),
        ("results/r0-opening-20261009/transport-kat.json", kat),
    ] {
        let path = root.join(path);
        if std::env::args().any(|x| x == "--check") {
            assert_eq!(
                std::fs::read_to_string(&path).unwrap(),
                expected,
                "{}",
                path.display()
            );
        } else {
            std::fs::write(path, expected).unwrap();
        }
    }
    println!("D13: 89 inactive pads legal in all 16 columns; pivot 1023 last; pi sha256={digest}");
}

"""Static missing-callee catalogue. Candidate discovery is not provenance admission."""
from pathlib import Path
import re,json,hashlib,subprocess
E=Path(__file__).resolve().parent
T=Path('evidence/extraction-assoc1-20261027/XRi_FunsExternal_Template.lean.txt')
RAW=Path('evidence/extraction-assoc2-20261027/XRj_L013/sources/XRj_generated/XRh_Release/Funs.lean')
sha=lambda b:hashlib.sha256(b).hexdigest()
names=re.findall(r'^axiom\s+([^\s:]+)',T.read_text(),re.M)
# External template itself exhaustively records all omitted declarations.
raw=RAW.read_text(); shipped=[n for n in names if n.startswith(('aspis_core.','verifier.','fast_pairing.','r1_','compact.','sampler.','aspis_statement.'))]
paths=subprocess.check_output(['rg','--files'],text=True).splitlines()
files=[Path(p) for p in paths if p.endswith(('.lean','.lean.txt')) and not p.startswith(str(E)+'/')]
index={n:{} for n in shipped}; scanned=0
for p in files:
 s=p.read_text(errors='replace')
 if 'AUTOMATICALLY GENERATED BY AENEAS' not in s:continue
 scanned+=1
 matches=list(re.finditer(r'(?m)^(?:noncomputable )?(?:def|abbrev|opaque)\s+([\w.]+)',s))
 for i,m in enumerate(matches):
  n=m[1]
  if n not in index:continue
  end=matches[i+1].start() if i+1<len(matches) else len(s)
  body=s[m.start():end]
  h=sha(body.encode()); row=index[n].setdefault(h,dict(declaration_span_sha256=h,paths=[],line=s[:m.start()].count('\n')+1,bytes=len(body.encode()),static_dropped_restoration=[]))
  row['paths'].append(str(p))
  # Conservative pattern flags; any flag demands manual review, not automatic fidelity.
  for j,line in enumerate(body.splitlines()):
   if re.search(r'let\s*\([^\n]*(?:next_back|back)[^\n]*_\)',line) or re.search(r'let\s*\([^\n]*_\)[^\n]*←[^\n]*(?:next|index_mut)',line):
    row['static_dropped_restoration'].append(dict(line=row['line']+j,text=line.strip()))
rows=[]
for n in shipped:
 rows.append(dict(name=n,template_line=T.read_text()[:re.search(r'^axiom\s+'+re.escape(n)+r'(?=\s|:)',T.read_text(),re.M).start()].count('\n')+1,referenced_in_raw=bool(re.search(r'(?<![\w.])'+re.escape(n)+r'(?![\w.])',raw)),candidates=list(index[n].values()),admitted=False,status='OPEN provenance and carrier association required' if index[n] else 'OPEN no generated candidate found in tracked scan'))
(E/'KSD_emitted_closure.json').write_text(json.dumps(dict(raw=str(RAW),raw_sha256=sha(RAW.read_bytes()),template=str(T),template_sha256=sha(T.read_bytes()),external_declarations=len(names),shipped_external_declarations=len(shipped),generated_files_scanned=scanned,method='exact external-template names; textual reference scan; generated-header candidate catalogue, not a proof of provenance',rows=rows),indent=2)+'\n')
print(json.dumps(dict(externals=len(names),shipped=len(shipped),scanned=scanned,with_candidates=sum(bool(r['candidates']) for r in rows),without_candidates=[r['name'] for r in rows if not r['candidates']])) )

#!/usr/bin/env python3
"""Generate public 1024-point constants; standard library only, exact arithmetic.
The original numerator tree and fixed nodes 1..271 are unchanged.
Run next to this script; --check verifies the already emitted Rust table.
"""
import argparse
from pathlib import Path
P = 2147483647
N = 1024

def add(x, y): return ((x[0]+y[0]) % P, (x[1]+y[1]) % P)
def sub(x, y): return ((x[0]-y[0]) % P, (x[1]-y[1]) % P)
def mul(x, y): return ((x[0]*y[0]-x[1]*y[1]) % P, (x[0]*y[1]+x[1]*y[0]) % P)
def power(x, n):
    out = (1, 0)
    while n:
        if n & 1: out = mul(out, x)
        x = mul(x, x)
        n >>= 1
    return out

def inv(x):
    norm = (x[0]*x[0]+x[1]*x[1]) % P
    assert norm != 0
    d = pow(norm, P-2, P)
    return (x[0]*d % P, -x[1]*d % P)

def fft(a, root):
    a = list(a)
    n = len(a)
    j = 0
    for i in range(1, n):
        bit = n >> 1
        while j & bit:
            j ^= bit
            bit >>= 1
        j ^= bit
        if i < j: a[i], a[j] = a[j], a[i]
    length = 2
    while length <= n:
        step = power(root, n//length)
        for base in range(0, n, length):
            w = (1, 0)
            for j in range(length//2):
                u, v = a[base+j], mul(a[base+j+length//2], w)
                a[base+j], a[base+j+length//2] = add(u, v), sub(u, v)
                w = mul(w, step)
        length *= 2
    return a

def generate():
    root = power((2, 1268011823), 1 << 21)
    assert power(root, 1024) == (1,0) and power(root,512) != (1,0)
    den = [1]
    for a in range(1,272):
        new = [0] * (len(den)+1)
        for j,c in enumerate(den):
            new[j] = (new[j]+c) % P
            new[j+1] = (new[j+1]-a*c) % P
        den = new
    spectrum = fft([(x,0) for x in den]+[(0,0)]*(N-len(den)), root)
    assert spectrum[0] == (0,0)
    assert all(x != (0,0) for x in spectrum[1:])
    inverses = [(0,0)] + [inv(x) for x in spectrum[1:]]
    for x,y in zip(spectrum[1:], inverses[1:]): assert mul(x,y) == (1,0)
    scales = [(1-pow(a,N,P)) % P for a in range(1,272)]
    assert scales[0] == 0 and all(scales[1:])
    dc = [N] + [(scales[a-1]*pow((1-a) % P, P-2, P)) % P for a in range(2,272)]
    for a,c in enumerate(dc,1):
        assert sum(pow(a,j,P) for j in range(N)) % P == c
    lines = ['// Generated by generate_cyclic_tables.py. Public constants only.',
             '// INV_DEN_1024[0] is a sentinel, NOT an inverse; replace FFT output 0 by DC.',
             f'// root1024 = CM31(M31({root[0]}), M31({root[1]})); ROOTS[2] in the retained 2048 table.']
    for name,values in [('COIN_SCALE_1024', scales), ('DC_WEIGHT_1024', dc)]:
        lines += [f'static {name}: [M31; 271] = [']
        lines += [f'    M31({x}),' for x in values]
        lines += ['];']
    lines += ['static INV_DEN_1024: [CM31; 1024] = [']
    lines += [f'    CM31 {{ a: M31({a}), b: M31({b}) }},' for a,b in inverses]
    lines += ['];', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args=p.parse_args()
    path=Path(__file__).with_name('r17_cyclic_tables.rs')
    content=generate()
    if args.check:
        assert path.read_text() == content, 'generated constants differ'
    else: path.write_text(content)
    print('PASS: root order, unique singular frequency, 1023 inverses, 271 geometric sums; '+('checked' if args.check else 'wrote')+' Rust constants')

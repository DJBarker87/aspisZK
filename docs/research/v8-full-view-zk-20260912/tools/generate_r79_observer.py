#!/usr/bin/env python3
"""Mechanically lift nine pinned sampler definitions to successful-call observation.

This is an explicit instrumentation trust boundary, NOT a certified compiler.
No control-flow or arithmetic source statement is deleted or reordered. Only
the result monad, local call names, loop operator and the two hash call sites
change. Actual field operations and parser/runtime helpers remain imported.
Source-location comments and preceding generated declaration attributes are
not copied onto the separately named observer definitions.
"""
import argparse, hashlib, json, re
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--patch',action='store_true');a=p.parse_args()
root=Path(__file__).resolve().parent.parent
src=root/'lean/AspisR72Sampler/Funs.lean'
pin='b693c4bc5c00835a3f0fe3ff2b895ce58f40c6a52cf6cfdfdac7beacde8e000e'
assert hashlib.sha256(src.read_bytes()).hexdigest()==pin
source=src.read_text()
assert source.count('self.hash ')==2
short=['squeeze_block','challenge_qm31_loop0_loop0.body','challenge_qm31_loop0_loop0',
       'challenge_qm31_loop0.body','challenge_qm31_loop0','challenge_qm31',
       'challenge_secure_circle_point_loop.body','challenge_secure_circle_point_loop',
       'challenge_secure_circle_point']
names={'transcript.Transcript.'+n:n for n in short}
# Do not rename the distinct generated error-mapping closure nested below
# challenge_secure_circle_point; it remains the actual imported helper.
pattern=re.compile(r'(?<![\w.])('+'|'.join(re.escape(n)for n in sorted(names,key=len,reverse=True))+r')(?![\w.])')
chunks=[]
for n in names:
    start=source.index('def '+n+'\n')
    end=source.index('\n/--',start)
    body=source[start:end].rstrip()+'\n'
    assert body.count('\n  Result ')==1,n
    body=body.replace('\n  Result ','\n  Observed ')
    body=pattern.sub(lambda m:names[m[0]],body)
    body=re.sub(r'(?<![\w.])ok(?=\s)', 'pure',body)
    body=re.sub(r'(?<![\w.])loop(?=\s)', 'observedLoop',body)
    body=body.replace('self.hash s4','observeHash self.hash s4').replace('self.hash s6','observeHash self.hash s6')
    chunks.append(body)
text='''import AspisV8R19.SamplerObservation

/-! Instrumented copy, NOT the original extracted definitions. Generated by
tools/generate_r79_observer.py from pinned R72 source; all computation and
control flow retained. Full source/observer correspondence is separate. -/
set_option autoImplicit false
namespace AspisV8R19.SamplerObservedSource
open Aeneas Aeneas.Std Result ControlFlow AspisR72Sampler SamplerObservation

'''+ '\n'.join(chunks)+'\nend AspisV8R19.SamplerObservedSource\n'
assert text.count('observeHash self.hash')==2
assert text.count('  observedLoop\n')==3
assert len(re.findall(r'^def ',text,re.M))==9
target=root/'lean/AspisV8R19/SamplerObservedSource.lean'
if a.patch:
    assert not target.exists()
    print('*** Begin Patch\n*** Add File: '+str(target))
    print('\n'.join('+'+line for line in text.splitlines()))
    print('*** End Patch')
else:
    assert target.read_text()==text
    print(json.dumps({'status':'PASS_SOURCE_INSTRUMENTATION_CHECK',
        'certified_compiler':False,'source_sha256':pin,'definitions':9,
        'hash_sites':2,'loops':3,'original_source_modified':False}))

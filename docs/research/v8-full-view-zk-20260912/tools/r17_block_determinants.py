#!/usr/bin/env python3
"""Emit/check small determinant leaves; never expand the 214-square matrix."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'evidence/r17-minor-blocks.jsonl'
ROWS = ROOT / 'evidence/r17-active-source-rows.json'
TARGET = ROOT / 'lean/AspisV8R17/BlockDeterminants.lean'

def render():
    raw = SOURCE.read_bytes()
    records = [json.loads(line) for line in raw.splitlines()]
    projection = json.loads(ROWS.read_text())
    assert len(projection['original_rows']) == len(projection['coefficient_indices']) == 214
    assert projection['original_rows'] == sorted(set(projection['original_rows']))
    assert len(set(projection['coefficient_indices'])) == 214
    assert all(0 <= r < 1023 for r in projection['original_rows'])
    assert all(100 <= j <= 1018 for j in projection['coefficient_indices'])
    assert len(records) == 133
    assert sorted(i for b in records for i in b['rows']) == list(range(214))
    assert sorted(i for b in records for i in b['columns']) == list(range(214))
    cases = []
    for b in records:
        n = len(b['rows'])
        assert n in (1, 2, 3) and len(b['columns']) == n and len(b['values']) == n*n
        assert all(isinstance(v, int) and 0 <= v < 2147483647 for v in b['values'])
        key = tuple(b['values'])
        if key not in cases:
            cases.append(key)
    assert len(cases) == 29
    out = ['import Mathlib.LinearAlgebra.Matrix.Determinant.Basic',
           'import Mathlib.Data.ZMod.Basic', '',
           '/-! Generated by tools/r17_block_determinants.py.',
           'Frozen input SHA256: '+hashlib.sha256(raw).hexdigest(),
           'Only 1x1/2x2/3x3 determinants; no dense determinant evaluation.',
           'Source/block composition is a separate obligation. -/',
           'set_option autoImplicit false', 'namespace AspisV8R17',
           'namespace BlockDeterminants', 'open Matrix', '']
    for i, values in enumerate(cases):
        n = {1: 1, 4: 2, 9: 3}[len(values)]
        rows = [' , '.join(map(str, values[r*n:(r+1)*n])) for r in range(n)]
        out += [f'def block{i} : Matrix (Fin {n}) (Fin {n}) (ZMod 2147483647) :=',
                '  !!['+'; '.join(rows)+']',
                f'theorem block{i}_det_ne_zero : block{i}.det ≠ 0 := by',
                '  rw [Matrix.det_fin_'+{1:'one',2:'two',3:'three'}[n]+']',
                '  decide',
                f'#print axioms block{i}_det_ne_zero', '']
    out += ['end BlockDeterminants', 'end AspisV8R17', '']
    return '\n'.join(out)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        assert TARGET.read_text() == expected, 'generated determinant leaves are stale'
        print('R17_BLOCK_DETERMINANTS_CHECK blocks=133 unique=29 max_dimension=3 match=true')
    else:
        print(expected, end='')

if __name__ == '__main__':
    main()

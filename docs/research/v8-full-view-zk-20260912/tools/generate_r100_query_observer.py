#!/usr/bin/env python3
"""Lift the pinned actual selected query entry, retaining the hash-free scan.

Explicit instrumentation boundary, not a certified compiler. Only the result
monad, local call names, loop operator and two hash calls change. The inner
scan stays the actual extracted Result computation, lifted without observation.
"""
import argparse,hashlib,json,re
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--patch',action='store_true');a=p.parse_args()
root=Path(__file__).resolve().parent.parent
src=root/'evidence/r98-native-query-entry/extraction/generated/AspisR98Query/Funs.lean'
pin='ea99abb7a248209c898308c966081fe931492238bf366a1c3cbf20a6af8ea90c'
assert hashlib.sha256(src.read_bytes()).hexdigest()==pin
source=src.read_text();assert source.count('self.hash ')==2
short=['squeeze_block','challenge_queries_without_replacement_loop0.body',
 'challenge_queries_without_replacement_loop0','challenge_queries_without_replacement']
names={'transcript.Transcript.'+n:n for n in short};names['query_probe']='query_probe'
pattern=re.compile(r'(?<![\w.])('+'|'.join(re.escape(n)for n in sorted(names,key=len,reverse=True))+r')(?![\w.])')
chunks=[]
for n in names:
    start=source.index('def '+n+'\n');end=source.find('\n/--',start)
    if end<0:end=source.index('\nend AspisR98Query',start)
    body=source[start:end].rstrip()+'\n';assert body.count('\n  Result ')==1,n
    body=body.replace('\n  Result ','\n  Observed ')
    body=pattern.sub(lambda m:names[m[0]],body)
    body=re.sub(r'(?<![\w.])ok(?=\s)','pure',body)
    body=re.sub(r'(?<![\w.])loop(?=\s)','observedLoop',body)
    body=body.replace('self.hash s4','observeHash self.hash s4').replace('self.hash s6','observeHash self.hash s6')
    chunks.append(body)
text='''import AspisV8R19.QueryEntrySource
import AspisV8R19.SamplerObservation

/-! Instrumented copy, NOT original extracted definitions. Generated by
generate_r100_query_observer.py from pinned R98 Funs. Arithmetic/control flow
retained; the hash-free inner scan is lifted unchanged. -/
set_option autoImplicit false
namespace AspisV8R19.QueryObservedSource
open Aeneas Aeneas.Std Result ControlFlow AspisR86Query SamplerObservation

'''+ '\n'.join(chunks)+'\nend AspisV8R19.QueryObservedSource\n'
assert text.count('observeHash self.hash')==2
assert text.count('  observedLoop\n')==1
assert len(re.findall(r'^def ',text,re.M))==5
target=root/'lean/AspisV8R19/QueryObservedSource.lean'
if a.patch:
    assert not target.exists()
    print('*** Begin Patch\n*** Add File: '+str(target))
    print('\n'.join('+'+line for line in text.splitlines()))
    print('*** End Patch')
else:
    assert target.read_text()==text
    print(json.dumps({'status':'PASS_SOURCE_INSTRUMENTATION_CHECK','certified_compiler':False,
      'source_sha256':pin,'definitions':5,'hash_sites':2,'loops':1,'inner_scan_unchanged':True}))

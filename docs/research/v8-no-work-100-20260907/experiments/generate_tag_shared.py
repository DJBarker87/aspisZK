#!/usr/bin/env python3
"""Reuse the pinned scatter DAG for every unweighted tag selector sum.

The old generator and all its outputs stay byte-identical. This emits a second
research entry point, sharing those exact 59 nodes in one call; not two calls
which rebuild the DAG. Only public frozen table data is consumed.
"""
import argparse,collections,contextlib,hashlib,io,json,runpy,sys
from pathlib import Path
EX=Path(__file__).resolve().parent
GEN=EX/'generate_copy_scatter.py'
assert hashlib.sha256(GEN.read_bytes()).hexdigest()=='4b8545fbf51a1f887baab09fcc3f39295a080337bd84832972d19c42d3818365'
ap=argparse.ArgumentParser();ap.add_argument('--write',action='store_true');ap.add_argument('--check',action='store_true');args=ap.parse_args()
assert args.write != args.check
saved=sys.argv;sys.argv=[str(GEN),'--check']
with contextlib.redirect_stdout(io.StringIO()): b=runpy.run_path(str(GEN))
sys.argv=saved
vectors=b['vectors'];original=[[] for _ in range(30)]
for g,p,h,f in b['ops']:original[g].append(h)
forms=[]
for hs in original:
    rem=collections.Counter(hs); form=[]
    while rem:
        candidates=[j for j,v in enumerate(vectors) if v<=rem]
        j=min(candidates,key=lambda j:(-sum(vectors[j].values()),j))
        form.append(j);rem-=vectors[j]
    assert sum((vectors[j] for j in form),collections.Counter())==collections.Counter(hs)
    forms.append(sorted(form))

source=b['outputs']['copy_scatter_plan_generated.rs']
start=source.index('#[inline(never)]\nfn research_fill_scatter(')
rust=source[start:].replace('fn research_fill_scatter(', 'fn research_fill_scatter_tag_shared(',1)
assert rust.endswith('}\n')
rust=rust[:-2]
for c,form in enumerate(forms):rust+=f'    scratch[{c}]={b["rsum"](form)};\n'
rust+='}\n'
rust='// Generated by generate_tag_shared.py; same scatter instructions, then tag sums.\n'+rust

lean=['import CopyScatterNodes','namespace AspisV8.CopyTagSums',
      'open AspisV8.CopyScatter','variable {K:Type*} [CommRing K]']
oldcells=[];newcells=[]
for c,(hs,form) in enumerate(zip(original,forms)):
    old='(0:K)'+''.join(f' + h {j}' for j in hs)
    new=b['lsum'](form)
    refs=sorted(set(j-64 for j in form if j>=64))
    lean+=[f'theorem coordinate{c} (h:Fin 64→K) : {old} = {new} := by']
    if refs:lean+=['  simp only ['+','.join(f'node{j}_spec' for j in refs)+'] <;> ring']
    else:lean+=['  ring']
    lean+=[f'#print axioms coordinate{c}'];oldcells.append(old);newcells.append(new)
# Keep the compiler's definitional lookup shallow, as in the previous plan.
for name,cells in [('original',oldcells),('shared',newcells)]:
    for start in (0,15):
        lean += [f'def {name}{start} (h:Fin 64→K) : Fin 15→K := ![', ',\n'.join(cells[start:start+15])+']']
    lean += [f'def {name} (h:Fin 64→K) (i:Fin 30) : K :=',
             f'  if hh:i.val<15 then {name}0 h ⟨i.val,hh⟩ else {name}15 h ⟨i.val-15,by omega⟩']
lean += ['theorem all_tag_sums (h:Fin 64→K) : original h=shared h := by', '  funext i','  fin_cases i']
lean += [f'  · exact coordinate{c} h' for c in range(30)]
lean += ['#print axioms all_tag_sums','end AspisV8.CopyTagSums']
meta={'schema':'aspis.research.tag-shared-plan.v1','table_sha256':b['TABLE_SHA'],
    'old_generator_sha256':hashlib.sha256(GEN.read_bytes()).hexdigest(),
    'old_rust_sha256':hashlib.sha256(source.encode()).hexdigest(),
    'same_59_nodes_computed_once':True,'direct_input_or_existing_node_sums':sum(len(x)==1 for x in forms),
    'extra_qm31_additions':sum(len(x)-1 for x in forms),'extra_heap_bytes':0,
    'reused_previously_unused_scratch_cells':30,'raw_s_limb_additions_removed':len(b['ops'])*4,
    'forms':forms,'literal_high_indices':original,'new_proof_bytes':0,'new_transcript_messages':0}
outputs={'copy_tag_shared_generated.rs':rust,'CopyTagSums.lean':'\n'.join(lean)+'\n',
         'copy-tag-shared-plan.json':json.dumps(meta,indent=2)+'\n'}
for name,body in outputs.items():
    if args.write:(EX/name).write_text(body)
    else:assert (EX/name).read_text()==body,f'stale generated file {name}'
print(json.dumps({k:v for k,v in meta.items() if k not in ('forms','literal_high_indices')},indent=2))

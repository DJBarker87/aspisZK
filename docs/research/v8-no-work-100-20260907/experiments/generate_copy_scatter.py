#!/usr/bin/env python3
"""Frozen-profile common-subexpression generation; exact integer certificates.

Only public table data is consumed. No field enumeration, witnesses or search
over proof transcripts. --check is the required generated-artifact preflight.
Generated sources are research-only and cannot activate production defaults.
"""
import argparse,collections,hashlib,itertools,json,re
from pathlib import Path
EX=Path(__file__).resolve().parent
ROOT=EX.parents[3]
src=ROOT/'crates/aspis-statement/src/pool_v1/pair_forest_copy_terminal.rs'
table=src.with_name('pair_forest_copy_terminal_constants.rs')
TABLE_SHA='cfce7ec499d3cfd54cf91eb88675e45d89ada5ce073fe00c78be5211204fbc50'
assert hashlib.sha256(table.read_bytes()).hexdigest()==TABLE_SHA
source=src.read_text(); text=table.read_text()
def array(name):
    body=re.search(r'const '+name+r':[^=]+?=\s*\[(.*?)\];',source,re.S)[1]
    assert re.fullmatch(r'[\s\d,]*',body),name
    return [int(x) for x in re.findall(r'\d+',body)]
gc=list(zip(array('COPY_GROUP_LOCAL_COORDINATE_GROUPS'),array('COPY_GROUP_LOCAL_COORDINATE_LOCALS')))
pc=list(zip(array('COPY_PATTERN_LOCAL_COORDINATE_GROUPS'),array('COPY_PATTERN_LOCAL_COORDINATE_LOCALS'),array('COPY_PATTERN_LOCAL_COORDINATE_PATTERNS')))
assert len(gc)==30 and len(pc)==43 and len(set(gc))==30 and len(set(pc))==43
endpoint=r'CompiledPoolV1PairForestEndpoint \{ row: (\d+), slot: (\d+), pattern: (\d+) \}'
pattern=r'CompiledPoolV1PairForestLink \{ tag: (\d+), weight_kind: (\d+), weight_level: (\d+), producer: '+endpoint+r', consumer: '+endpoint+r' \}'
links=[tuple(map(int,m)) for m in re.findall(pattern,text)]
assert len(links)==136
flags=sorted(set((x[1],x[2]) for x in links))
ops=[]
for tag,kind,level,pr,ps,pp,cr,cs,cp in links:
    assert kind in range(5) and level<64 and tag<2147483647
    for side,row,slot,pat in ((0,pr,ps,pp),(2,cr,cs,cp)):
        assert row<1024 and slot<2 and pat<14
        ops.append((gc.index((side+slot,row%16)),pc.index((side+slot,row%16,pat)),row//16,flags.index((kind,level))))

# Keys: (scratch coordinate, flag), with -1 meaning an unconditional pattern.
original={}; cell_ops=collections.defaultdict(list)
for g,p,h,f in ops:
    original.setdefault((30+g,f),[]).append(h)
    original.setdefault((60+p,-1),[]).append(h)
    cell_ops[30+g].append((f,h));cell_ops[60+p].append((-1,h))
forms={key:sorted(value) for key,value in sorted(original.items())}
nodes=[]
while True:
    scores=collections.Counter()
    for xs in forms.values():
        count=collections.Counter(xs)
        for a,b in itertools.combinations_with_replacement(sorted(count),2):
            uses=count[a]//2 if a==b else min(count[a],count[b])
            if uses: scores[(a,b)]+=uses
    if not scores: break
    pair,uses=min(scores.items(),key=lambda x:(-x[1],x[0]))
    if uses<=1: break
    a,b=pair; fresh=64+len(nodes);nodes.append(pair)
    for key,xs in forms.items():
        while a in xs and b in xs and (a!=b or xs.count(a)>=2):
            xs.remove(a);xs.remove(b);xs.append(fresh)
        xs.sort()

# Independently evaluate every DAG node in the free commutative additive monoid.
vectors=[collections.Counter({j:1}) for j in range(64)]
for a,b in nodes:
    assert a<len(vectors) and b<len(vectors)
    vectors.append(vectors[a]+vectors[b])
for key,xs in forms.items():
    assert sum((vectors[x] for x in xs),collections.Counter())==collections.Counter(original[key])

def rnode(j): return f'h[{j}]' if j<64 else f'n[{j-64}]'
def rsum(xs):
    if not xs: return 'QM31::ZERO'
    mid=len(xs)//2
    if len(xs)==1:return rnode(xs[0])
    return f'{rsum(xs[:mid])}.add({rsum(xs[mid:])})'
def lnode(j): return f'h {j}' if j<64 else f'node{j-64} h'
def lsum(xs,fn=lnode):return ' + '.join(fn(x) for x in xs) or '(0:K)'
def expanded(xs):
    v=sum((vectors[x] for x in xs),collections.Counter())
    return [j for j,n in sorted(v.items()) for _ in range(n)]
def flag_expr(kind,level):
    return ['true','variant == PoolV1PairForestCompiledVariantV1::PrivateTransfer',
        'variant == PoolV1PairForestCompiledVariantV1::Withdrawal',
        f'(append_index >> {level}) & 1 == 0',f'(append_index >> {level}) & 1 != 0'][kind]

rust=['// Generated by generate_copy_scatter.py --write. Do not edit.',f'// COPY_LINKS source SHA256: {TABLE_SHA}',
      f'const RESEARCH_SCATTER_FLAG_COUNT:usize={len(flags)};',
      f'const RESEARCH_SCATTER_FLAG_KEYS:[(u8,u8);{len(flags)}]=[{",".join(str(x) for x in flags)}];',
      '#[inline(never)]',
      'fn research_scatter_flags(append_index:u64,variant:PoolV1PairForestCompiledVariantV1)->[bool;RESEARCH_SCATTER_FLAG_COUNT]{',
      '    ['+',\n     '.join(flag_expr(*f) for f in flags)+']','}',
      '#[inline(never)]',
      'fn research_fill_scatter(scratch:&mut[QM31],selectors:&Selectors,flags:&[bool;RESEARCH_SCATTER_FLAG_COUNT]){',
      '    assert_eq!(scratch.len(),COPY_SELECTOR_TENSOR_SCRATCH);',
      '    let h=&selectors.high;',f'    let mut n=vec![QM31::ZERO;{len(nodes)}];']
for j,(a,b) in enumerate(nodes):rust.append(f'    n[{j}]={rnode(a)}.add({rnode(b)});')
for c in range(30,103):
    keys=[k for k in forms if k[0]==c]
    parts=[rsum(forms[k]) if k[1]<0 else f'(if flags[{k[1]}] {{ {rsum(forms[k])} }} else {{ QM31::ZERO }})' for k in keys]
    val=parts[0] if parts else 'QM31::ZERO'
    for part in parts[1:]:val=f'{val}.add({part})'
    rust.append(f'    scratch[{c}]={val};')
rust+=['}']

lean=['import Mathlib.Tactic',f'-- Frozen table SHA256 {TABLE_SHA}',
      'namespace AspisV8.CopyScatter','variable {K : Type*} [CommRing K]',
      'theorem bool_weight (b:Bool) (x:K) : (if b then x else 0)=(if b then (1:K) else 0)*x := by cases b <;> simp',
      'theorem zero_cell : (0:K)=0 := Eq.refl 0']
for j,(a,b) in enumerate(nodes):
    lean += [f'def node{j} (h:Fin 64→K) : K := {lnode(a)} + {lnode(b)}',
        f'theorem node{j}_spec (h:Fin 64→K) : node{j} h = {lsum(expanded([64+j]))} := by']
    specs=[f'node{x-64}_spec' for x in sorted(set((a,b))) if x>=64]
    lean += [f'  simp only [node{j}'+(' ,'+','.join(specs) if specs else '')+'] <;> ring']
lean+=['#print axioms bool_weight']
lean += [f'#print axioms node{j}_spec' for j in range(len(nodes))]
lean+=['end AspisV8.CopyScatter']

# Small coordinate certificates reuse named node specifications. No giant
# generated numeral, domain enumeration or recursive recurrence unfolding.
chunks={}; old_cells=[]; new_cells=[]
for start in (30,55,80):
    lines=['import CopyScatterNodes','namespace AspisV8.CopyScatter','variable {K : Type*} [CommRing K]']
    for c in range(start,min(start+25,103)):
        keys=[k for k in forms if k[0]==c]
        old='(0:K)'+''.join(' + '+(f'w {f} * (h {h})' if f>=0 else f'h {h}') for f,h in cell_ops[c])
        new=' + '.join((f'w {f} * ({lsum(forms[(cc,f)])})' if f>=0 else f'({lsum(forms[(cc,f)])})') for cc,f in keys) or '(0:K)'
        refs=sorted(set(x-64 for k in keys for x in forms[k] if x>=64))
        lines += [f'theorem coordinate{c} (h:Fin 64→K) (w:Fin {len(flags)}→K) :',f'    {old} = {new} := by']
        if not keys:lines+=['  exact zero_cell']
        else:
            if refs:lines+=['  simp only ['+','.join(f'node{j}_spec' for j in refs)+'] <;> ring']
            else:lines+=['  ring']
        lines+=[f'#print axioms coordinate{c}']
        old_cells.append(old);new_cells.append(new)
    lines+=['end AspisV8.CopyScatter']
    chunks[f'CopyScatterCells{start}.lean']='\n'.join(lines)+'\n'

bridge=['import CopyScatterCells30','import CopyScatterCells55','import CopyScatterCells80',
    'namespace AspisV8.CopyScatter','variable {K : Type*} [CommRing K]']
# Keep the lookup depth bounded. A monolithic 73-entry vecCons table makes
# definitional reduction recurse through a long prefix when using the final
# coordinate certificates; three small tables avoid that reduction shape.
for name,cells in [('originalCells',old_cells),('planCells',new_cells)]:
    for start in (0,25,50):
        part=cells[start:start+25]
        bridge += [f'def {name}{start} (h:Fin 64→K) (w:Fin {len(flags)}→K) : Fin {len(part)}→K := ![',',\n'.join(part)+']']
    bridge += [f'def {name} (h:Fin 64→K) (w:Fin {len(flags)}→K) (i:Fin 73) : K :=',
        f'  if h0:i.val<25 then {name}0 h w ⟨i.val,h0⟩',
        f'  else if h1:i.val<50 then {name}25 h w ⟨i.val-25,by omega⟩',
        f'  else {name}50 h w ⟨i.val-50,by omega⟩']
bridge += [f'theorem all_modified_cells (h:Fin 64→K) (w:Fin {len(flags)}→K) : originalCells h w=planCells h w := by',
    '  funext i','  fin_cases i']
bridge += [f'  · exact coordinate{c} h w' for c in range(30,103)]
bridge += ['#print axioms all_modified_cells','end AspisV8.CopyScatter']
chunks['CopyScatterPlan.lean']='\n'.join(bridge)+'\n'

metadata={'schema':'aspis.research.copy-scatter-plan.v1','table_sha256':TABLE_SHA,'links':len(links),'endpoints':len(ops),
  'flag_keys':flags,'original_additive_terms':sum(map(len,original.values())),
  'shared_addition_nodes':len(nodes),'remaining_form_additions':sum(max(0,len(x)-1) for x in forms.values()),
  'weighted_group_combination_additions':sum(max(0,sum(cc==c for cc,f in forms)-1) for c in range(30,60)),
  'weighted_groups':sum(f>=0 for c,f in forms),'pattern_forms':sum(f<0 for c,f in forms),
  'scratch_bytes_unchanged':103*16,'additional_node_heap_bytes':len(nodes)*16,
  'independent_integer_vector_checks':True,'new_proof_bytes':0,'new_transcript_messages':0,
  'nodes':nodes,'forms':{f'{c}:{f}':v for (c,f),v in forms.items()}}
outputs={'copy_scatter_plan_generated.rs':'\n'.join(rust)+'\n','CopyScatterNodes.lean':'\n'.join(lean)+'\n',
    **chunks,'copy-scatter-plan.json':json.dumps(metadata,indent=2)+'\n'}
ap=argparse.ArgumentParser();ap.add_argument('--write',action='store_true');ap.add_argument('--check',action='store_true');args=ap.parse_args()
assert args.write!=args.check,'choose --write or --check'
for name,body in outputs.items():
    path=EX/name
    if args.write:path.write_text(body)
    else:assert path.read_text()==body, f'stale generated file {path}'
print(json.dumps({k:v for k,v in metadata.items() if k not in ('nodes','forms','flag_keys')},indent=2))

#!/usr/bin/env python3
"""Generate bounded 64-entry table certificates, never expand the full domain."""
import argparse,json
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
root=Path(__file__).resolve().parent
data=json.loads((root/'circle-window-points.json').read_text())
lines=['-- Generated by generate_circle_norm_tables.py; exact public source table snapshot.',
       'import CircleNorm','namespace AspisV8.CircleNormTables',
       'open AspisV8.CircleNorm','abbrev F := ZMod 2147483647']
for name,rows in data.items():
    assert len(rows)==64
    assert all(0<=x<2147483647 and 0<=y<2147483647 and (x*x+y*y)%2147483647==1 for x,y in rows)
    lines += [f'def {name}Data : List (UnitPoint F) := [']
    for i,(x,y) in enumerate(rows):
        # Each field certificate reduces just two products, not a recurrence.
        lines += [f'  ⟨({x},{y}), by dsimp [unit]; decide⟩'+(',' if i<63 else ']')]
    lines += [f'theorem {name}_length : {name}Data.length=64 := by rfl',
              f'def {name} (i : Fin 64) : UnitPoint F :=',
              f'  {name}Data[i.val]\'(by simpa only [{name}_length] using i.isLt)',
              f'#print axioms {name}']
lines += [
 'def selected (i j k : Fin 64) : UnitPoint F :=',
 '  windows (low i) (middle j) (high k) (j.val != 0) (k.val != 0)',
 'theorem selected_unit (i j k : Fin 64) : unit (selected i j k).val :=',
 '  (selected i j k).property',
 'theorem selected_even (i j k : Fin 64) (a b c : F) :',
 '    a+b*(selected i j k).val.1^2+c*(selected i j k).val.2^2 =',
 '      (a+c)+(b-c)*(selected i j k).val.1^2 :=',
 '  point_endpoint (selected i j k) a b c',
 'theorem selected_norms {R : Type*} [CommRing R] (embed : F →+* R)',
 '    (i j k : Fin 64) (r a b c d e f : R) :',
 '    let x := embed (selected i j k).val.1',
 '    let y := embed (selected i j k).val.2',
 '    (ChordNorm.norm r (a+c*x+e*y) (b+d*x+f*y),',
 '     ChordNorm.norm r (a+c*x-e*y) (b+d*x-f*y),',
 '     ChordNorm.norm r (a-c*x-e*y) (b-d*x-f*y),',
 '     ChordNorm.norm r (a-c*x+e*y) (b-d*x+f*y)) =',
 '    (let t := (ChordNorm.norm r a b+ChordNorm.norm r e f)+',
 '       (ChordNorm.norm r c d-ChordNorm.norm r e f)*x^2',
 '     let u := ChordNorm.polar r a b c d*x',
 '     let v := ChordNorm.polar r a b e f*y',
 '     let w := ChordNorm.polar r c d e f*(x*y)',
 '     ((t+u)+(v+w),(t+u)-(v+w),(t-u)-(v-w),(t-u)+(v-w))) := by',
 '  exact CircleNorm.four_slots _ _ _ _ _ _ _ _ _',
 '    (map_unit embed _ _ (selected_unit i j k))',
 '#print axioms selected_unit','#print axioms selected_even','#print axioms selected_norms',
 'end AspisV8.CircleNormTables']
out='\n'.join(lines)+'\n'
if a.check: assert (root/'CircleNormTables.lean').read_text()==out
else: print(out,end='')

#!/usr/bin/env python3
"""Frozen straight-line offset plans, with bounded arithmetic and certificates."""
import argparse,collections,contextlib,hashlib,io,json,runpy,sys
from pathlib import Path
EX=Path(__file__).resolve().parent;GEN=EX/'generate_copy_scatter.py'
assert hashlib.sha256(GEN.read_bytes()).hexdigest()=='4b8545fbf51a1f887baab09fcc3f39295a080337bd84832972d19c42d3818365'
ap=argparse.ArgumentParser();ap.add_argument('--write',action='store_true');ap.add_argument('--check',action='store_true');args=ap.parse_args()
assert args.write != args.check
saved=sys.argv;sys.argv=[str(GEN),'--check']
with contextlib.redirect_stdout(io.StringIO()):b=runpy.run_path(str(GEN))
sys.argv=saved
literal=[[] for _ in range(30)]
for i,link in enumerate(b['links']):
    tag,kind,level,pr,ps,pp,cr,cs,cp=link
    assert tag==(67<<24)+i and 0<=i<136
    for side,row,slot in ((0,pr,ps),(2,cr,cs)):
        coordinate=b['gc'].index((side+slot,row%16))
        literal[coordinate].append((row//16,i))
assert sum(map(len,literal))==272
# Omit only literal coefficient zero, not a witness-dependent zero.
plans=[[(h,c) for h,c in xs if c] for xs in literal]
for xs,ys in zip(literal,plans):
    def vector(seq):
        v=collections.Counter()
        for h,c in seq:v[h]+=c
        return +v
    assert vector(xs)==vector(ys)
    assert len(ys)<=272 and all(0<=h<64 and 0<c<136 for h,c in ys)

def tree(xs,leaf,zero,add):
    if not xs:return zero
    if len(xs)==1:return leaf(*xs[0])
    m=len(xs)//2
    return add(tree(xs[:m],leaf,zero,add),tree(xs[m:],leaf,zero,add))
def rust(xs,limb):
    def leaf(h,c):
        a=f'u64::from(h[{h}].{limb}.0)'
        return a if c==1 else f'{a}.wrapping_mul({c})'
    return tree(xs,leaf,'0u64',lambda l,r:f'{l}.wrapping_add({r})')
def lean(xs):
    return tree(xs,lambda h,c:f'(.term {h} ⟨{c},by decide⟩)','.zero',lambda l,r:f'(.add {l} {r})')
rs=['// Generated by generate_tag_offsets.py --write. Frozen public coefficients only.',
    '#[inline(never)]','fn research_copy_tag_offsets(coordinate:usize,h:&[QM31;64])->[u64;4]{','    match coordinate {']
for c,xs in enumerate(plans):
    rs += [f'        {c} => [',',\n'.join('            '+rust(xs,limb) for limb in ('c0.a','c0.b','c1.a','c1.b'))+'],']
rs += ['        _ => unreachable!("frozen tag coordinate"),','    }','}']

ls=['import CopyTagOffsetModel','namespace AspisV8.CopyTagOffset']
for c,(original,plan) in enumerate(zip(literal,plans)):
    old='0'+''.join(f' + h {h} * {a}' for h,a in original)
    ls += [f'def plan{c} : Plan := {lean(plan)}',
        f'theorem count{c} : count plan{c} ≤ 272 := by decide',
        f'theorem value{c} (h:Fin 64→Nat) : eval h plan{c} = {old} := by']
    if plan:ls+= [f'  simp only [plan{c},eval]; ring']
    else:ls+= [f'  simp only [plan{c},zero_plan]; ring']
    ls += [f'theorem machine{c} (h:Fin 64→Nat) (hh:∀ i,h i<AspisV8.CopyTagSplit.p) : machine h plan{c}={old} := by',
           f'  rw [machine_exact h hh plan{c} count{c},value{c}]',f'#print axioms machine{c}']
ls += ['def select0 : Fin 15→Plan := !['+','.join(f'plan{c}' for c in range(15))+']',
       'def select15 : Fin 15→Plan := !['+','.join(f'plan{c}' for c in range(15,30))+']',
       'def select (i:Fin 30) : Plan :=',
       '  if hh:i.val<15 then select0 ⟨i.val,hh⟩ else select15 ⟨i.val-15,by omega⟩']
ls += ['theorem every_selected_plan_count (i:Fin 30) : count (select i)≤272 := by','  fin_cases i']
ls += [f'  · exact count{c}' for c in range(30)]
ls += ['theorem every_machine_exact (i:Fin 30) (h:Fin 64→Nat) (hh:∀ j,h j<AspisV8.CopyTagSplit.p) :',
       '    machine h (select i)=eval h (select i) := machine_exact h hh (select i) (every_selected_plan_count i)',
       '#print axioms every_selected_plan_count','#print axioms every_machine_exact','end AspisV8.CopyTagOffset']
meta={'schema':'aspis.research.tag-offset-plan.v1','table_sha256':b['TABLE_SHA'],
      'literal_terms':272,'emitted_terms':sum(map(len,plans)),
      'zero_coefficients_removed':272-sum(map(len,plans)),
      'maximum_plan_terms':max(map(len,plans)),'zero_plans':[c for c,xs in enumerate(plans) if not xs],
      'balanced_additions_per_limb':sum(max(0,len(xs)-1) for xs in plans),
      'coefficient_one_multiplies_omitted_per_limb':sum(c==1 for xs in plans for h,c in xs),
      'no_heap_or_protocol_changes':True,'literal':literal,'plans':plans}
outputs={'copy_tag_offsets_generated.rs':'\n'.join(rs)+'\n','CopyTagOffsetPlans.lean':'\n'.join(ls)+'\n',
         'copy-tag-offset-plan.json':json.dumps(meta,indent=2)+'\n'}
for name,body in outputs.items():
    if args.write:(EX/name).write_text(body)
    else:assert (EX/name).read_text()==body,f'stale generated output {name}'
print(json.dumps({k:v for k,v in meta.items() if k not in ('literal','plans')},indent=2))

#!/usr/bin/env python3
"""Exact declaration union of actual public preparation; no caller simulation."""
from pathlib import Path
import argparse,hashlib,importlib.util,json,re,subprocess,tempfile
ROOT=Path(__file__).resolve().parents[5]
HERE=Path(__file__).resolve().parent
REV='b92ab28465f9ffd4edcd3e2d5300cc9306ba66af'
BASE='docs/research/100bit-spend-path-20261013/tools/public-serializer-extraction-kit/extract.py'
sha=lambda b:hashlib.sha256(b).hexdigest()
def blob(repo,revision,path):
 return subprocess.check_output(['git','-C',str(repo),'show',revision+':'+path])
def main():
 ap=argparse.ArgumentParser(description=__doc__)
 ap.add_argument('--repo',type=Path,default=ROOT);ap.add_argument('--out',type=Path,default=HERE)
 ap.add_argument('--check',action='store_true');a=ap.parse_args()
 parser=a.repo/BASE;parser_bytes=parser.read_bytes();assert parser_bytes==blob(a.repo,REV,BASE)
 spec=importlib.util.spec_from_file_location('source_cut',parser)
 old=importlib.util.module_from_spec(spec);spec.loader.exec_module(old)
 items=old.ITEMS+[
  ('digest_trait','crates/aspis-core/src/digest.rs','pub trait Digest32: Copy'),
  ('terminal_common','crates/aspis-statement/src/pool_v1/pair_forest_terminal.rs','pub struct PoolV1PairForestTerminalCommonV1'),
  ('terminal_statement','crates/aspis-statement/src/pool_v1/pair_forest_terminal.rs','pub enum PoolV1PairForestTerminalStatementV1'),
  ('semantic_public_method','crates/aspis-statement/src/pool_v1/pair_forest_terminal.rs','pub fn semantic_public(&self)'),
  ('wire_error','crates/aspis-r1-cost-probe/src/r1_wire.rs','pub enum Error'),
  ('domain_plain','crates/aspis-r1-cost-probe/src/r1_wire.rs','#[cfg(not(feature = "private-leaf-salts"))]\npub const DOMAIN'),
  ('domain_salted','crates/aspis-r1-cost-probe/src/r1_wire.rs','#[cfg(feature = "private-leaf-salts")]\npub const DOMAIN'),
  ('transcript_type','crates/aspis-r1-cost-probe/src/r1_wire.rs','pub struct SemanticTranscript<H: Digest32>'),
  ('transcript_new','crates/aspis-r1-cost-probe/src/r1_wire.rs','pub fn new(hash: H, public_bytes:'),
  ('public_transcript','crates/aspis-r1-cost-probe/src/r1_semantic.rs','pub fn public_transcript<H: Digest32>'),
 ]
 outputs={};cuts=[];sources={}
 with tempfile.TemporaryDirectory(prefix='aspis-public-cut-') as scratch:
  for i,(name,path,anchor) in enumerate(items):
   raw=blob(a.repo,REV,path);sources[path]=sha(raw)
   f=Path(scratch)/(str(i)+'.rs');f.write_bytes(raw)
   b,start,end,line,last=old.find_item(f,anchor)
   assert raw[start:end]==b
   outputs['fragments/'+name+'.rs']=b
   cuts.append({'name':name,'path':path,'start_byte':start,'end_byte_exclusive':end,'start_line':line,'end_line_exclusive':last,'sha256':sha(b)})
 layout=(HERE/'layout.template.rs').read_bytes();parts=[];spans=[];offset=0
 for line in layout.splitlines(keepends=True):
  match=re.fullmatch(rb'\s*include!\("fragments/([a-z0-9_]+)\.rs"\);\n?',line)
  if match:
   name=match[1].decode();part=outputs['fragments/'+name+'.rs']
   spans.append({'name':name,'start_byte':offset,'end_byte_exclusive':offset+len(part),'sha256':sha(part)})
   if not part.endswith(b'\n'):part+=b'\n'
  else:part=line
  parts.append(part);offset+=len(part)
 assert {x['name'] for x in spans}=={x['name'] for x in cuts} and len(spans)==len(cuts)
 outputs['lib.rs']=b''.join(parts)
 outputs['Cargo.toml']=b'''[package]
name = "aspis-r1-public-preparation"
version = "0.0.0"
edition = "2021"
publish = false
[lib]
path = "lib.rs"
[features]
default = []
r0 = []
private-leaf-salts = []
[workspace]
'''
 outputs['Cargo.lock']=b'''# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "aspis-r1-public-preparation"
version = "0.0.0"
'''
 pins={'revision':REV,'source_files':sources,'cuts':cuts,'layout_spans':spans,'layout_sha256':sha(layout),'source_cut_parser':{'path':BASE,'sha256':sha(parser_bytes)},'kit_files':{n:sha(b) for n,b in outputs.items()},'features':['r0','private-leaf-salts'],'closure':'Exact serializer declarations plus actual semantic_public, public_transcript and SemanticTranscript::new; Digest32 remains a trait parameter. No observer, verifier tail, account/SDK carrier or QM arithmetic is extracted.','open':['Outer first/tx1/verify_observed success-to-helper execution','Rust/tool/runtime preservation','R16 digest semantics','Accounts/custody']}
 outputs['source-pins.json']=(json.dumps(pins,indent=2,sort_keys=True)+'\n').encode()
 for name,b in outputs.items():
  f=a.out/name
  if a.check:assert f.read_bytes()==b,name
  else:f.parent.mkdir(parents=True,exist_ok=True);f.write_bytes(b)
 print(json.dumps({'checked':a.check,'cuts':len(cuts),'source_files':len(sources),'lines':outputs['lib.rs'].count(b'\n'),'lib_sha256':sha(outputs['lib.rs']),'revision':REV}))
if __name__=='__main__':main()

#!/usr/bin/env python3
"""Project the exact safe std Vec wrapper over its opaque RawVec buffer type."""
from pathlib import Path
import argparse,hashlib,json
ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
tool=Path(__file__).resolve().parent;out=tool/'rho-empty-reserve-input';sha=lambda b:hashlib.sha256(b).hexdigest()
method=b'''    pub fn try_reserve_exact(&mut self, additional: usize) -> Result<(), TryReserveError> {
        self.buf.try_reserve_exact(self.len, additional)
    }'''
origin=json.loads((tool/'rho-empty-reserve-source/origin.json').read_text())
full=tool/'rho-empty-reserve-source/vec-mod.rs'
source=(full if full.exists() else tool/'rho-empty-reserve-source/vec-used-slices.rs').read_bytes()
source_hash=origin['full_source_sha256']
if full.exists():assert sha(source)==source_hash
else:assert sha(source)==origin['slice_sha256']
assert method in source
fields=b'''    buf: RawVec<T, A>,
    len: usize,''';assert fields in source
# B is exactly the wrapper's opaque RawVec<T,A> field. Its arbitrary operation
# is a computational parameter, not a frame/success/equivalence assumption.
lib=b'''pub struct VecProjection<B> {pub buf:B,pub len:usize}
pub trait RawReserve {
    type ReserveError;
    fn try_reserve_exact(&mut self,len:usize,additional:usize)->Result<(),Self::ReserveError>;
}
pub fn source_reserve<B:RawReserve>(value:&mut VecProjection<B>,additional:usize)->Result<(),B::ReserveError> {
        value.buf.try_reserve_exact(value.len, additional)
}
'''
body=lib.split(b'pub fn source_reserve')[1].split(b'{',1)[1].rsplit(b'}',1)[0].strip()
assert body==method.split(b'{',1)[1].rsplit(b'}',1)[0].strip().replace(b'self',b'value')
outputs={'lib.rs':lib,'Cargo.toml':b'[package]\nname="aspis-r1-rho-empty-reserve"\nversion="0.0.0"\nedition="2021"\n[lib]\npath="lib.rs"\n[workspace]\n','Cargo.lock':b'# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "aspis-r1-rho-empty-reserve"\nversion = "0.0.0"\n'}
meta={'source':'nightly-2026-06-01 alloc/src/vec/mod.rs','std_source_sha256':source_hash,'source_method_sha256':sha(method),'source_fields_sha256':sha(fields),'transport':['Receiver self -> standalone value, B := actual opaque RawVec<T,A> field.','Actual RawVec try_reserve_exact(len,additional) is an arbitrary shared mutable-buffer operation.','No raw buffer semantics/frame/success law is assumed. Only outer Vec.len frame is proved; empty logical contents follow from length zero.'],'kit_files':{n:sha(b) for n,b in outputs.items()}}
outputs['source-pins.json']=(json.dumps(meta,indent=2)+'\n').encode()
for n,b in outputs.items():
 p=out/n
 if a.check:assert p.read_bytes()==b,n
 else:p.parent.mkdir(exist_ok=True,parents=True);p.write_bytes(b)
print(json.dumps({'check':a.check,'lib_sha256':sha(lib)}))

#!/usr/bin/env python3
"""Read/hash the retained checked cone; never compile or promote a cache."""
from pathlib import Path
import hashlib,json,tarfile
base=Path(__file__).resolve().parent
sha=lambda data:hashlib.sha256(data).hexdigest()
manifest=json.loads((base/'manifest.json').read_text())
archive=base/manifest['archive']
assert sha(archive.read_bytes())==manifest['archive_sha256']
with tarfile.open(archive,'r:gz') as tf:
    files={m.name:tf.extractfile(m).read() for m in tf if m.isfile()}
assert len(files)==manifest['archive_entries']
for line in files['SHA256SUMS'].decode().splitlines():
    digest,name=line.split('  ',1)
    assert sha(files[name])==digest,name
for name,record in manifest['modules'].items():
    source='sources/'+name.replace('.','/')+'.lean'
    assert sha(files[source])==record['source_sha256']
    receipt=json.loads(files[record['receipt']])
    assert receipt['exit_status']==0 and receipt['axioms']['passed']
    assert receipt['key']['source_sha256']==record['source_sha256']
    assert receipt['process_swaps']==0 and receipt['cgroup_swap_current']=='0'
    for suffix,obj in receipt['objects'].items():
        assert sha(files['objects/'+name.replace('.','/')+suffix])==obj['sha256']
assert not any('WithdrawalSuccess' in n for n in files)
for name,digest in [('Types','5ac27c38f74aa4cbeb7ad1c224ae0cf9fa324458f591f8ee57604371b8f01d7e'),('Funs','36b3603e86f5fc332c7a02f470c5a5af34febf0e5142e666c6300ce82b215bab')]:
    assert sha(files['sources/AspisR1TerminalValidator/'+name+'.lean'])==digest
    assert files['original/'+name+'.lean']==files['sources/AspisR1TerminalValidator/'+name+'.lean']
    assert b'Slice.Insts.CoreCmpPartialEqArray.eq' not in files['original/'+name+'.lean']
llbc=json.loads(files['original/TerminalValidator.llbc'])['translated']
t=next(t for t in llbc['type_decls'] if t and t['def_id']==28)
assert [(v['name'],v['discriminant']) for v in t['kind']['Enum']]==[('None',{'Scalar':{'Signed':['Isize','0']}}),('Some',{'Scalar':{'Signed':['Isize','1']}})]
print(f"PASS: {len(files)} archive entries; five checked modules; exact generated bytes/tags; failed attempts retained")

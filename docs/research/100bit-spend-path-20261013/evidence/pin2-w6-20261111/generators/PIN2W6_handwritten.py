"""PIN2 W6: value-carrying HANDWRITTEN fixture modules (no committed generator).
Each module is regenerated by substituting, in the 26 October release text,
exactly the literals that are a function of the checkpoint bytes; every
substitution site is matched by a pattern that must occur the stated number
of times.  check mode: values computed from the 26 October checkpoint (research
lean/JFx_DataCheckpoint00.lean) must reproduce the release text byte for byte;
pin2 mode: values from the PIN2 checkpoint (W4 sources/RPz8_JFx_DataCheckpoint00).
Cross-check: the checkpoint words equal the native dump (queries = tag 5
indices 0..21, gamma = tag 4 index 27) in both modes.
  python3 -I PIN2W6_handwritten.py check|pin2"""
import sys, re, json, hashlib, subprocess
from pathlib import Path
H = Path(__file__).resolve().parent.parent
W = Path('/Users/dominic/ZK/.worktrees/pin2-lean'); EV = H.parent
sys.path.insert(0, str(H / 'tools'))
import PIN2W6_src as S
mode = sys.argv[1]
sha = lambda b: hashlib.sha256(b).hexdigest()
git = lambda *a: subprocess.run(['git', '-C', str(W), *a], capture_output=True, check=True).stdout
if mode == 'check':
    ck_src = git('show', 'research:lean/JFx_DataCheckpoint00.lean').decode()
    V = json.load(open(EV / 'pin2-w5-20261111/provenance-26oct/DERIVED-26OCT.json'))
else:
    ck_src = (EV / 'pin2-w4-20261111/sources/RPz8_JFx_DataCheckpoint00.lean').read_text()
    V = json.load(open(EV / 'pin2-w5-20261111/PIN2W5_VALUES.json'))
ck = [int(v) for cell in re.findall(r'def c\d+ : List U8 := \[([^\]]*)\]', ck_src) for v in re.findall(r'(\d+)#u8', cell)]
assert len(ck) == 1768
le = lambda bs: int.from_bytes(bytes(bs), 'little')
queries = [le(ck[320 + 4 * i: 324 + 4 * i]) for i in range(22)]
gamma = [le(ck[176 + 4 * i: 180 + 4 * i]) for i in range(8)]
assert queries == [V['tx1']['5'][str(i)][0] for i in range(22)], 'checkpoint queries != native tag 5'
assert gamma == V['tx1']['4']['27'], 'checkpoint gamma != native tag 4/27'
def sub(text, pattern, repl, count):
    new, n = re.subn(pattern, repl, text, flags=re.M)
    assert n == count, (pattern, n, count)
    return new
def qwords(t):
    for i in range(22):
        bs = ck[320 + 4 * i: 324 + 4 * i]
        t = sub(t, rf'^(def b{i} : Array U8 4#usize := ⟨)\[[0-9#u8,]+\](,rfl⟩)$', lambda m: m[1] + '[' + ','.join(f'{b}#u8' for b in bs) + ']' + m[2], 1)
        t = sub(t, rf'^(theorem word{i} : core\.num\.U32\.from_le_bytes b{i}=)\d+(#u32 := rfl)$', lambda m: m[1] + str(queries[i]) + m[2], 1)
    return t
def qvalue(t):
    return sub(t, r'^(def value : Array U32 22#usize := Array\.make 22#usize )\[[0-9#u32,]+\]$', lambda m: m[1] + '[' + ','.join(f'{q}#u32' for q in queries) + ']', 1)
def gcanon(t):
    g = gamma
    t = sub(t, r'^(  change \(\()\d+( < 2147483647 ∧ )\d+( < 2147483647\) ∧)$', lambda m: f'{m[1]}{g[0]}{m[2]}{g[1]}{m[3]}', 1)
    t = sub(t, r'^(    \()\d+( < 2147483647 ∧ )\d+( < 2147483647\)\) ∧)$', lambda m: f'{m[1]}{g[2]}{m[2]}{g[3]}{m[3]}', 1)
    t = sub(t, r'^(    \(\()\d+( < 2147483647 ∧ )\d+( < 2147483647\) ∧)$', lambda m: f'{m[1]}{g[4]}{m[2]}{g[5]}{m[3]}', 1)
    t = sub(t, r'^(    \()\d+( < 2147483647 ∧ )\d+( < 2147483647\)\))$', lambda m: f'{m[1]}{g[6]}{m[2]}{g[7]}{m[3]}', 1)
    return t
MODS = {'RPt_JFq_QueryWords': qwords, 'RPt_JFq_Queries': qvalue, 'RPt_JFo_GammaCanonical': gcanon}
rep = dict(mode=mode, checkpoint_sha256=sha(bytes(ck)), queries=queries, gamma=gamma, modules=[])
for m, fn in MODS.items():
    rel, note = S.release(m); rel = rel.decode()
    out = fn(rel)
    row = dict(module=m, release_source=note, release_sha256=sha(rel.encode()), out_sha256=sha(out.encode()), text_changed=out != rel)
    if mode == 'check':
        assert out == rel, m + ': check mode does not reproduce the release text'
    else:
        (H / 'sources').mkdir(exist_ok=True); (H / 'sources' / f'{m}.lean').write_text(out); row['written'] = f'sources/{m}.lean'
    rep['modules'].append(row)
(H / f'HANDWRITTEN-{mode}.json').write_text(json.dumps(rep, indent=1) + '\n')
print(mode, 'ok', [(r['module'], r['text_changed']) for r in rep['modules']])

def sub(text, pattern, repl, count):
    new, n = re.subn(pattern, repl, text, flags=re.M)
    assert n == count, (pattern, n, count)
    return new
def qwords(t):
    for i in range(22):
        bs = ck[320 + 4 * i: 324 + 4 * i]
        t = sub(t, rf'^(def b{i} : Array U8 4#usize := ⟨)\[[0-9#u8,]+\](,rfl⟩)$', lambda m: m[1] + '[' + ','.join(f'{b}#u8' for b in bs) + ']' + m[2], 1)
        t = sub(t, rf'^(theorem word{i} : core\.num\.U32\.from_le_bytes b{i}=)\d+(#u32 := rfl)$', lambda m: m[1] + str(queries[i]) + m[2], 1)
    return t
def qvalue(t):
    return sub(t, r'^(def value : Array U32 22#usize := Array\.make 22#usize )\[[0-9#u32,]+\]$', lambda m: m[1] + '[' + ','.join(f'{q}#u32' for q in queries) + ']', 1)

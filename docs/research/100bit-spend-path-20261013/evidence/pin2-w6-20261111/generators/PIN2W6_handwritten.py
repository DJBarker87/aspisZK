    t = sub(t, r'^(    \()\d+( < 2147483647 ∧ )\d+( < 2147483647\)\) ∧)$', lambda m: f'{m[1]}{g[2]}{m[2]}{g[3]}{m[3]}', 1)
    t = sub(t, r'^(    \(\()\d+( < 2147483647 ∧ )\d+( < 2147483647\) ∧)$', lambda m: f'{m[1]}{g[4]}{m[2]}{g[5]}{m[3]}', 1)
    t = sub(t, r'^(    \()\d+( < 2147483647 ∧ )\d+( < 2147483647\)\))$', lambda m: f'{m[1]}{g[6]}{m[2]}{g[7]}{m[3]}', 1)
    return t

"""Classify the unbuilt in-closure fixture modules by whether their release
source text can carry a 26 October fixture value.
  regen-W4/W5 : a PIN2 source already regenerated by W4/W5 (text changed)
  literal     : the release source has an integer literal >= 2^16 that is not
                the field modulus or a SHA-256 constant/IV; 'native' if it is a
                limb of the 26 October native dump (W5 provenance)
  small-literal-list: a list literal of >= 8 small numbers (byte/word data)
  generic     : neither (refers to fixture values by name only)
usage: python3 -I PIN2W6_classify.py <scan_dir> <out.json>"""
import sys, os, re, json, collections, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.argv = [sys.argv[0], sys.argv[1], sys.argv[2]]
out_path = sys.argv[2]; sys.argv = sys.argv[:2]
import PIN2W6_ready as R, PIN2W6_src as S
EV = S.EV
D = json.load(open(EV / 'pin2-w5-20261111/provenance-26oct/DERIVED-26OCT.json'))
where = collections.defaultdict(set)
for st in ('tx1', 'tx2'):
    for t, v in D[st].items():
        for i, x in v.items():
            for limb in x:
                if limb >= 1 << 16: where[limb].add(f'{st}:tag{t}')
sha_src = subprocess.run(['git', '-C', str(S.W), 'show', 'research:lean/JFp_SHA256.lean'], capture_output=True).stdout.decode()
SKIP = {2147483647, 2147483648, 4294967295, 4294967296, 65536, 18446744073709551615}
SKIP |= set(map(int, re.search(r'def constants : List Nat := \[(.*?)\]', sha_src, re.S)[1].replace('\n', '').split(',')))
SKIP |= {1779033703, 3144134277, 1013904242, 2773480762, 1359893119, 2600822924, 528734635, 1541459225}
w4 = {f[:-5] for f in os.listdir(EV / 'pin2-w4-20261111/sources')}
w5 = {f[:-5] for f in os.listdir(EV / 'pin2-w5-20261111/sources')}
rows = {}
todo = sorted(m for m in R.dep if R.FIX.match(m) and not R.inW4(m))
for m in todo:
    b, note = S.release(m)
    if b is None: rows[m] = dict(cls='no-release-source'); continue
    s = b.decode()
    body = re.sub(r'--.*', '', s)
    big = [int(n) for n in re.findall(r'(?<![\w.])\d{5,}(?![\w.])', body) if int(n) >= 1 << 16 and int(n) not in SKIP]
    nat = sum(1 for n in big if n in where)
    lists = len(re.findall(r'\[(?:\s*\d+\s*(?:#u8|#u32|#usize)?\s*,){7,}', body))
    cls = 'regen-W5' if m in w5 else 'regen-W4' if m in w4 else 'literal' if big else 'small-literal-list' if lists else 'generic'
    rows[m] = dict(cls=cls, big=len(big), native=nat, lists=lists, src=note)
c = collections.Counter(r['cls'] for r in rows.values())
print(len(rows), dict(c))
fam = collections.defaultdict(collections.Counter)
for m, r in rows.items(): fam[re.sub(r'\d+', '#', m)][r['cls'] + ('/nat' if r.get('native') else '')] += 1
for k, v in sorted(fam.items()):
    if set(v) != {'generic'}: print(f'  {k:42s}', dict(v))
json.dump(rows, open(out_path, 'w'), indent=1)

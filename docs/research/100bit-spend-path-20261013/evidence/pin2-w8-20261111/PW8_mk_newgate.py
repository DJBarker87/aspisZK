#!/usr/bin/env python3
"""PW8: PIN2_NEWGATE_verifyprefix.lean (lead option A: twin PIN2 types, consistent with the overlay PIN2_NEWGATE_r0/_r1_semantic).
Sections, all generated by this script:
 1. Aeneas text of every PW8_E004 declaration (PIN2 pair, c7593d23fdc) that the overlay NEWGATE files do not already define,
    with PCXU's xform; declarations already in the overlay are dropped after a token-identity assertion (resolved by import).
    Dropped as unreferenced: aspis_core.field.QM31.Insts.CoreCloneClone (its method is an external axiom; no declaration uses it).
    Any @[discriminant isize] is expanded by the W3c CLASH-FIX rule (definition + explicitly named instance in the namespace).
 2. PrefixAdapter: the frozen nominal adapter ExtractedPrefixParseCore (toOld/fromOld/errorFromOld/parseAccepted/parse_success)
    copied with only its namespace changed to AspisR1PublicPreparationPIN2.PrefixAdapter (so Prefix/r1_wire.Error resolve to
    the PIN2 carriers; the parser stays AspisR1PrefixAggregateParser.r1_wire.Prefix.parse, r1_wire.rs unchanged since 4bb3b3f).
 3. VerifyPrefix.Finish/mark/verify: output_text of PW8_SUBSTITUTION.json (scripted fe80 map + binder + RPz7 Phase swap + tool map
    on the PW8_E003 emission), checked against its recorded sha.
usage: python3 PW8_mk_newgate.py <overlay PIN2_NEWGATE_r0.lean> <overlay PIN2_NEWGATE_r1_semantic.lean> <frozen ExtractedPrefixParseCore.lean>"""
import sys,re,json
sys.dont_write_bytecode=True
from PW8_lib import *
N0,N1,EPC=sys.argv[1:4]
assert sha(open(N0,'rb').read())=='949d0070883f92f9ae9a0a49c57c165a1feec4a430334602f2897471f61488bd'
assert sha(open(N1,'rb').read())=='b0a096b056f8c68bf64832a97cb1c65c5d09e771eca992304ee9ef75c7390fc6'
epc=open(EPC).read()
R='PW8_E004_emitted/raw/PW8_vp/'
raw={f:open(R+f).read() for f in ['Types.lean','Funs.lean','FunsExternal_Template.lean']}
ng=gate_blocks(N0);ng.update(gate_blocks(N1))
DROP_UNREF={'aspis_core.field.QM31.Insts.CoreCloneClone'}
kept=[];dropped_identical=[];dropped_unref=[];out=[]
allb=[b for f in ['Types.lean','Funs.lean'] for b in blocks(xform(inner(raw[f],'PW8_vp')))]
keys=[key(b) for b in allb]
for b in allb:
    k=key(b);assert k
    if k in ng:
        assert norm(ng[k])==norm(b),('STOP: overlay NEWGATE text differs',k);dropped_identical.append(k);continue
    if k in DROP_UNREF:
        assert not any(re.search(r'(?<![\w.])'+re.escape(k)+r'(?![\w.])',re.sub(r'(?s)^/--.*?-/\n','',x)) for x in allb if key(x)!=k),k
        dropped_unref.append(k);continue
    if '@[discriminant' in b:raise SystemExit('discriminant attribute in a kept declaration: apply CLASH-FIX (not needed so far) '+k)
    kept.append(k);out.append(b)
# no kept declaration may reference an external axiom of the emission
ext=re.findall(r'(?m)^axiom (\S+)',raw['FunsExternal_Template.lean'])
for b in out:
    for e in ext:assert not re.search(r'(?<![\w.])'+re.escape(e)+r'(?![\w.])',b),('kept declaration uses an external',key(b),e)
# PrefixAdapter copy
a=epc.index('namespace AspisR1PublicPreparation.PrefixAdapter');z=epc.index('end AspisR1PublicPreparation.PrefixAdapter')
adapter=epc[a:z].replace('namespace AspisR1PublicPreparation.PrefixAdapter','namespace AspisR1PublicPreparationPIN2.PrefixAdapter',1)+'end AspisR1PublicPreparationPIN2.PrefixAdapter\n'
assert 'AspisR1PublicPreparation.' not in adapter.replace('AspisR1PublicPreparationPIN2.','')
# VerifyPrefix from the substitution record
U=json.load(open('PW8_SUBSTITUTION.json'));ot=U['output_text']
assert sha('\n\n'.join(ot[k] for k in sorted(ot)))==U['output_sha256']
vp='\n\n'.join([ot['VerifyPrefix.Finish'],ot['VerifyPrefix.mark'],ot['VerifyPrefix.verify']])
hdr='''-- PIN2 NEW GATE for the verifier prefix (VerifyPrefix.verify = r1_semantic::verify_observed under the recorded fe80/RPz7 substitution)
-- at source c7593d23fdc56fcee9a9df1628d5f63b52ac7a95. Lead option A: twin PIN2 types, composed with the overlay PIN2_NEWGATE_r0/_r1_semantic.
-- Section 1: emission PW8_E004, Charon 454586e9 + Aeneas 0d21a9ec, overflow-checks ON, features private-leaf-salts,optimized-terminal,program-build,
--   cargo --jobs 4 / CARGO_BUILD_JOBS=4, rustc -Zthreads=1, identity by class receipt PCWE_E003; raw sha256 Types.lean %s Funs.lean %s.
-- Section 2: PrefixAdapter = frozen ExtractedPrefixParseCore (sha256 %s), namespace changed only.
-- Section 3: VerifyPrefix from PW8_SUBSTITUTION.json (input PW8_E003 Funs.lean sha256 %s, Charon daad69be + Aeneas b59d5188-lean432-extended; output sha256 %s).
-- Built by PW8_mk_newgate.py; declarations of the overlay NEWGATE files are imported, not repeated. No placeholder proof, no axiom.
import Aeneas
import PIN2_NEWGATE_r1_semantic
import AspisR1PrefixAggregateParser.Funs
import RPz7_PhaseIso
open Aeneas Aeneas.Std Result ControlFlow Error
set_option linter.dupNamespace false
set_option linter.hashCommand false
set_option linter.unusedVariables false
set_option linter.style.whitespace false
set_option linter.style.setOption false
set_option linter.style.longLine false
set_option maxRecDepth 2048

/- Aeneas-generated default heartbeat budget for the emitted definitions (same as PIN2_NEWGATE_r0/_r1_semantic). -/
set_option maxHeartbeats 1000000

namespace AspisR1PublicPreparationPIN2

'''%(sha(raw['Types.lean']),sha(raw['Funs.lean']),sha(epc),U['input']['sha256'],U['output_sha256'])
txt=hdr+'\n\n'.join(out)+'\n\nend AspisR1PublicPreparationPIN2\n\nset_option maxHeartbeats 200000\n\n'
txt+='/-! Section 2: PrefixAdapter (scripted copy of ExtractedPrefixParseCore with the PIN2 namespace). -/\nset_option autoImplicit false\nopen Aeneas Aeneas.Std Result\n'+adapter
txt+='\nnamespace AspisR1PublicPreparationPIN2\n\n/-! Section 3: VerifyPrefix (PW8_SUBSTITUTION.json). -/\n'+vp+'\n\nend AspisR1PublicPreparationPIN2\n\n'
for n in ['r1_wire.begin','r1_wire.SemanticTranscript.semantic_validated','PrefixAdapter.parseAccepted','VerifyPrefix.mark','VerifyPrefix.verify']:
    txt+='#print axioms AspisR1PublicPreparationPIN2.%s\n'%n
assert 'so'+'rry' not in txt and not re.search(r'(?m)^axiom ',txt)
open('PIN2_NEWGATE_verifyprefix.lean','w').write(txt)
json.dump(dict(kept=kept,dropped_identical_to_overlay=dropped_identical,dropped_unreferenced=dropped_unref,emission_externals=ext,adapter_source_sha256=sha(epc),substitution_output_sha256=U['output_sha256'],sha256=sha(txt)),open('PW8_NEWGATE_DECLS.json','w'),indent=1)
print(len(txt),sha(txt),'kept',len(kept),'dropped',len(dropped_identical),'unref',dropped_unref)

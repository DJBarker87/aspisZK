//! Regenerate the fixed monomial-truncation correction; off-chain only.
use aspis_core::{
    field::M31,
    r0::basis::{BasisSize, NaturalBasis},
};
fn main() {
    assert!(!cfg!(debug_assertions), "use --release --features r0");
    let basis = NaturalBasis::new(BasisSize::Initial).unwrap();
    let mut d = vec![M31::ZERO; 513];
    d[1] = M31::ONE;
    let mut degree = 1;
    for _ in 0..9 {
        let mut next = vec![M31::ZERO; 513];
        for i in 0..=degree {
            for j in 0..=degree {
                next[i + j] = next[i + j].add(d[i].mul(d[j]).double());
            }
        }
        next[0] = next[0].sub(M31::ONE);
        d = next;
        degree *= 2;
    }
    let mut t = vec![M31::ZERO; 512];
    basis.monomial_to_natural(&d[..512], &mut t).unwrap();
    println!("// Generated by cargo run --release -p aspis-core --features r0 --example r0_weight_table.");
    println!("// Natural coefficients of D_9 minus its degree-512 monomial. Do not hand edit.");
    println!("pub const TOP_OVERFLOW: [u32; 512] = [");
    for row in t.chunks(8) {
        for x in row {
            print!("{}, ", x.0);
        }
        println!();
    }
    println!("]; ");
}
